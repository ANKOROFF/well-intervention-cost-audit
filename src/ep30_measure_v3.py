"""Measures of C, the expanding price per tonne and CAPEX shares by pump outcome."""
from __future__ import annotations
import config as cfg
import pathlib
import sys
import polars as pl
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import ep19_crossruler as e19
import stats
from ep30_crossacct import ОЖИД, сверить, якорь
B = 1000000000.0
M = 1000000.0
ПОРОГ = 0.02
LINE = e19.LINE
ФАКТ = cfg.data('interim/capex_physical.parquet')
TSV_С = cfg.out('ep30_measure_v3_C.tsv')
TSV_Ц = cfg.out('ep30_measure_v3_price.tsv')
TSV_Н = cfg.out('ep30_measure_v3_pump.tsv')

def часть_c(цепь_ids: set) -> None:
    ф = pl.read_parquet(ФАКТ)
    пп = pl.read_parquet(e19.CAP_ПП)
    print('\n=== 13.1. C И ДИАПАЗОН ЛЕТ ===')
    print(f"  факт-таблица: {ф.height} операций, C = {ф['capex'].sum() / M:.1f} млн руб")
    якорь('C все годы млн', ф['capex'].sum() / M, '.1f')
    якорь('C операций', ф.height, 'd')
    строки = ['срез\tопераций\tCAPEX_млн']
    for имя, усл in (('год >= 2016', pl.col('год') >= 2016), ('2016-2024', pl.col('год').is_between(2016, 2024)), ('год >= 2025', pl.col('год') >= 2025), ('год < 2016', pl.col('год') < 2016)):
        t = ф.filter(усл)
        s, n = (t['capex'].sum() / M, t.height)
        print(f"  {имя:12s}: {n:5d} операций, {s:10.1f} млн руб, {100 * s / (ф['capex'].sum() / M):.2f}% C")
        строки.append(f'{имя}\t{n}\t{s:.1f}')
        к = {'год >= 2016': '2016+', '2016-2024': '2016-2024', 'год >= 2025': '2025+', 'год < 2016': 'до 2016'}[имя]
        якорь(f'C {к} млн', s, '.1f')
        якорь(f'C {к} операций', n, 'd')
        якорь(f'C {к} доля C', s / (ф['capex'].sum() / M), '.4f')
    for к in ('год', 'vnr', 'end', 'beg'):
        якорь(f'пул {к} минимум', ф[к].min().year if к != 'год' else ф[к].min(), 'd')
        якорь(f'пул {к} максимум', ф[к].max().year if к != 'год' else ф[к].max(), 'd')
        print(f'  диапазон {к}: {ф[к].min()} .. {ф[к].max()}')
    for имя, t in (('ППП-таблица', пп), ('цепь ППП', пп.filter(pl.col('op_id').is_in(list(цепь_ids))))):
        t16 = t.filter(pl.col('год') >= 2016)
        print(f"  {имя}: {t.height} операций, CAPEX {t['capex'].sum() / M:.1f} млн; 2016+: {t16.height} операций, {t16['capex'].sum() / M:.1f} млн; годы {t['год'].min()}..{t['год'].max()}")
        якорь(f'{имя} операций', t.height, 'd')
        якорь(f'{имя} CAPEX млн', t['capex'].sum() / M, '.1f')
        якорь(f'{имя} 2016+ операций', t16.height, 'd')
        якорь(f'{имя} 2016+ CAPEX млн', t16['capex'].sum() / M, '.1f')
    pathlib.Path(TSV_С).write_text('\n'.join(строки) + '\n', encoding='utf-8')

def часть_насос(цепь_ids: set) -> None:
    print('\n=== 13.3. ДОЛИ ПО СЛУЧАЯМ НАСОСА (операций и CAPEX) ===')
    ф = pl.read_parquet(ФАКТ)
    пп = pl.read_parquet(e19.CAP_ПП)
    наборы = (('факт-таблица', ф), ('ППП-таблица', пп), ('цепь ППП', пп.filter(pl.col('op_id').is_in(list(цепь_ids)))))
    строки = ['совокупность\tслучай\tопераций\tдоля_операций\tCAPEX_млн\tдоля_CAPEX']
    for имя, t in наборы:
        N, S = (t.height, t['capex'].sum())
        t = t.with_columns(сл=pl.col('насос_случай').str.slice(0, 1))
        if имя == 'факт-таблица':
            t = t.with_columns(сл=pl.when((pl.col('сл') == 'в') & pl.col('мат_измерены')).then(pl.lit('в1 материал из других драйверов')).when(pl.col('сл') == 'в').then(pl.lit('в2 подстановка медианы типа')).otherwise(pl.col('сл')))
        print(f'  {имя}: {N} операций, CAPEX {S / M:.1f} млн')
        г = t.group_by('сл').agg(n=pl.len(), c=pl.col('capex').sum()).sort('сл')
        for сл, n, c in г.iter_rows():
            print(f'    {сл:34s} {n:5d} оп. ({100 * n / N:5.2f}%)  {c / M:10.1f} млн ({100 * c / S:5.2f}% CAPEX)')
            строки.append(f'{имя}\t{сл}\t{n}\t{n / N:.4f}\t{c / M:.1f}\t{c / S:.4f}')
            якорь(f'насос {имя} {сл} операций', n, 'd')
            якорь(f'насос {имя} {сл} доля операций', n / N)
            якорь(f'насос {имя} {сл} доля CAPEX', c / S)
        якорь(f'насос {имя} всего операций', N, 'd')
    pathlib.Path(TSV_Н).write_text('\n'.join(строки) + '\n', encoding='utf-8')

def часть_цена(наш) -> int:
    print('\n=== 13.2. РАСШИРЯЮЩАЯСЯ ЦЕНА ТОННЫ, ЦЕПЬ ППП ===')
    g0 = наш['линии'][LINE]
    ок = all([сверить('GC(ППП)', g0['GC'], ОЖИД['GC_НН']), сверить('GC(ППП) ДИ низ', g0['lo'], ОЖИД['lo_НН']), сверить('GC(ППП) ДИ верх', g0['hi'], ОЖИД['hi_НН']), сверить('знаменатель Н', наш['разрыв'], ОЖИД['знам_Н'])])
    if not ок or наш['n'] != e19.N_ОБЪЯВЛЕНО or наш['лет'] != 9:
        print('ОСТАНОВ по п. 0.3 правил: регрессия не сошлась.')
        return 1
    d, руб_т = stats.build(e19.параметры(e19.CAP_ПП))
    цены = {}
    исходный = stats.year_run

    def обёртка(d_, руб_т_, Y, *a, **k):
        цены[Y] = float((d_.filter(pl.col('год') < Y)['доход_диск'] / d_.filter(pl.col('год') < Y)['inc_oil_t'].abs().clip(1, None)).median())
        return исходный(d_, цены[Y], Y, *a, **k)
    stats.year_run = обёртка
    try:
        нов = e19.прогон_exante('расширяющаяся цена тонны', e19.параметры(e19.CAP_ПП))
    finally:
        stats.year_run = исходный
    g1 = нов['линии'][LINE]
    print(f'  глобальная цена тонны (stats.build, ППП): {руб_т:,.0f} руб/т')
    print(f"  {'год Y':>6s} {'расш. цена,руб/т':>17s} {'к глобальной':>13s}")
    строки = ['Y\tрасш_цена_руб_т\tотношение_к_глобальной']
    for Y in sorted(цены):
        print(f'  {Y:6d} {цены[Y]:17,.0f} {цены[Y] / руб_т:13.3f}')
        строки.append(f'{Y}\t{цены[Y]:.0f}\t{цены[Y] / руб_т:.4f}')
        якорь(f'расш. цена тонны {Y} руб', цены[Y], '.0f')
    якорь('глобальная цена тонны ППП руб', руб_т, '.0f')
    ΔGC = g1['GC'] - g0['GC']
    print(f"  GC: глобальная цена {g0['GC']:.4f} [{g0['lo']:.4f}, {g0['hi']:.4f}] -> расширяющаяся {g1['GC']:.4f} [{g1['lo']:.4f}, {g1['hi']:.4f}], повторов {g1['повторов']}, ДМ {g1['ДМ']:.2f}, p = {g1['p']:.4f}")
    print(f"  NPV линии: {g0['NPV']:.4f} -> {g1['NPV']:.4f} млрд; знаменатель {наш['разрыв']:.4f} -> {нов['разрыв']:.4f}; отобрано {g0['оп']} -> {g1['оп']}; n {нов['n']}")
    знам_ок = abs(нов['разрыв'] - наш['разрыв']) < 1e-06
    print(f"  знаменатель не изменился: {('да' if знам_ок else 'НЕТ -- подлежит докладу')}")
    код = 'З-1' if abs(ΔGC) <= ПОРОГ else 'З-2'
    print(f'\n  ΔGC = {ΔGC:+.4f}; порог {ПОРОГ}')
    print(f'  НАСТУПИЛ ИСХОД {код} -- ' + ('заглядывание вперёд через цену тонны несущественно' if код == 'З-1' else 'заглядывание вперёд через цену тонны существенно'))
    якорь('GC расширяющаяся цена', g1['GC'])
    якорь('GC расширяющаяся цена ДИ низ', g1['lo'])
    якорь('GC расширяющаяся цена ДИ верх', g1['hi'])
    якорь('GC расширяющаяся цена повторов', g1['повторов'], 'd')
    якорь('GC расширяющаяся цена ДМ', g1['ДМ'], '.2f')
    якорь('GC расширяющаяся цена p', g1['p'])
    якорь('NPV линии расширяющаяся цена млрд', g1['NPV'])
    якорь('отобрано операций расширяющаяся цена', g1['оп'], 'd')
    якорь('знаменатель расширяющаяся цена млрд', нов['разрыв'])
    якорь('ΔGC расширяющаяся минус глобальная', ΔGC, '+.4f')
    якорь('номер исхода (1 З-1, 2 З-2)', 1 if код == 'З-1' else 2, 'd')
    pathlib.Path(TSV_Ц).write_text('\n'.join(строки) + '\n', encoding='utf-8')
    return 0

def главная() -> int:
    print('=== Б13: C 2016+, расширяющаяся цена тонны, доли CAPEX по насосу; цепь ППП ===')
    print('правило чтения: docs/epic/b1_reading_rules.md, раздел 11 (записано до расчёта)')
    наш = e19.прогон_exante('НАША (объёмная, ex-ante цепь ППП)', e19.параметры(e19.CAP_ПП))
    ids = set(наш['d']['op_id'].to_list())
    rc = часть_цена(наш)
    if rc:
        return rc
    часть_c(ids)
    часть_насос(ids)
    print('\nЧЕГО ЗАМЕР НЕ ДЕЛАЕТ: головное число не меняет; расширяющаяся медиана не объявляется правильнее глобальной; CAPEX не пересчитывается.')
    return 0
if __name__ == '__main__':
    sys.exit(главная())
