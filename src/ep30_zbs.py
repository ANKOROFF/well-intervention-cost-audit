"""Sidetrack package: drilling-rate grid."""
import config as cfg
import csv
import pathlib
import sys
import numpy as np
import polars as pl
ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'src'))
import ep19_crossruler as e19
from ep06_ablation import _ряд_линейкой, _цены
from sdt_analysis import отборы_линии, расхождение, цепь
TOL, HALF = (0.0001, 0.084)
V0 = 40.0
СТАНОК = 1.0
ЯЧЕЙКИ = [('П1', 40.0), ('П2', None), ('П5', 20.0), ('П7', 80.0), ('Г1', 2.36), ('Г2', 401.0)]
OUT_MD = ROOT / cfg.results('ep30_zbs.md')
OUT_TSV = ROOT / cfg.out('ep30_zbs.tsv')
ПРОЧЬ = []

def вывод(s=''):
    ПРОЧЬ.append(s)
    print(s, flush=True)

def якорь(имя, знач, ф='.4f'):
    вывод(f'ЯКОРЬ {имя} = {format(знач, ф)}')

def сценарий(cap, v):
    return cap.with_columns(capex=pl.col('capex') + pl.when(pl.col('тип') == 'ЗБС').then(pl.col('проходка_м') * (1.0 / v - 1.0 / V0) * СТАНОК).otherwise(0.0))

def исход(lo, d):
    if lo <= 0:
        return 'W'
    return 'S' if abs(d) <= HALF else 'Д'

def main() -> int:
    cap = pl.read_parquet(e19.CAP_ПП)
    збс = set(cap.filter(pl.col('тип') == 'ЗБС')['op_id'].to_list())
    c40 = сценарий(cap, V0)
    отн = float(((c40['capex'] - cap['capex']).abs() / cap['capex'].abs().clip(1.0, None)).max())
    print(f'РЕГРЕССИЯ пересчёта CAPEX при v=40: макс. относительное отклонение {отн:.2e}')
    if отн > 1e-09:
        print('ОСТАНОВ: пересчёт CAPEX при v=40 не воспроизводит capex')
        return 1
    рез = {}
    for имя, v in ЯЧЕЙКИ:
        c = cap.filter(pl.col('тип') != 'ЗБС') if v is None else сценарий(cap, v)
        наш, л1 = цепь(имя, c)
        рез[имя] = (наш, л1)
        g = наш['линии'][e19.LINE]
        print(f"{имя}: n {наш['n']}, GC {g['GC']:.4f} [{g['lo']:.4f}, {g['hi']:.4f}]", flush=True)
        if имя == 'П1':
            ok = abs(g['GC'] - 0.2631) <= TOL and abs(g['lo'] - 0.1772) <= TOL and (abs(g['hi'] - 0.3453) <= TOL) and (наш['n'] == 5806) and (наш['лет'] == 9) and (abs(наш['разрыв'] - float('nan')) <= TOL)
            print(f"РЕГРЕССИЯ П1: {('сошлась' if ok else 'НЕ СОШЛАСЬ')}")
            if not ok:
                print('ОСТАНОВ: регрессия на головное число не сошлась')
                return 1
        if имя == 'П2':
            ok = abs(g['GC'] - 0.2544) <= TOL and abs(g['lo'] - 0.1909) <= TOL and (abs(g['hi'] - 0.3161) <= TOL) and (наш['n'] == 5533)
            print(f"РЕГРЕССИЯ П2: n {наш['n']}, {('сошлась' if ok else 'НЕ СОШЛАСЬ')}")
            if not ok:
                print('ОСТАНОВ: регрессия П2 (ведомость, sdt_analysis.md) не сошлась')
                return 1
    ids_цепи = set(рез['П1'][0]['d']['op_id'].to_list())
    з = cap.filter(pl.col('тип') == 'ЗБС')
    мед = float(з['проходка_м'].median())
    флаг_таблица = int((з['проходка_м'] != мед).sum())
    флаг_цепь = int(з.filter(pl.col('op_id').is_in(list(ids_цепи)))['проходка_м'].ne(мед).sum())
    физ = pl.read_parquet(ROOT / cfg.data('interim/capex_physical.parquet')).filter(pl.col('тип') == 'ЗБС')
    мед_физ = float(физ['проходка_м'].median())
    инфо_физ = int((физ['проходка_м'] != мед_физ).sum())
    инфо_физ_цепь = int(физ.filter(pl.col('op_id').is_in(list(ids_цепи)))['проходка_м'].ne(мед_физ).sum())
    п4_ok = флаг_таблица == 50 and з.height == 373
    вывод('# Б1.4. Пакет ЗБС (ep30_zbs)')
    вывод('')
    вывод(f'Цепь ППП, регрессии сошлись: П1 0.2631 [0.1772, 0.3453] n 5806, знаменатель <withheld>; П2 0.2544 [0.1909, 0.3161] n 5533; capex*(40) = capex (отклонение {отн:.1e}). Скорости 20/40/80 - сетка x0.5/x1/x2 от НАЗНАЧЕННОЙ базовой 40 м/сут, не из литературы; скорость меняет только деньги (длительность и ёмкость не пересчитываются).')
    вывод('')
    вывод('| ячейка | n | лет | GC | lo | hi | повт. | ДМ | p | dGC к П1 | знаменатель | операций отбора | расх. отбора с Л1 | Жаккар с Л1 | доля ЗБС в расх. | ДОР-Л1 (справ.) | исход S/Д/W | С |')
    вывод('|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|')
    g1 = рез['П1'][0]['линии'][e19.LINE]
    tsv, итог = ([], {})
    for имя, v in ЯЧЕЙКИ:
        наш, л1 = рез[имя]
        g = наш['линии'][e19.LINE]
        d = g['GC'] - g1['GC']
        a, b = (отборы_линии(наш), отборы_линии(л1))
        р = расхождение(a, b, збс)
        X, Xз, I, U = (sum((x[k] for x in р.values())) for k in range(4))
        нотб = sum((len(s) for s in a.values()))
        дор = e19.доля(_ряд_линейкой(наш['отборы'], _цены(л1), e19.LINE), л1['df']['факт инженеров|NPV'].to_numpy(), л1['df']['оракул по факту|NPV'].to_numpy())
        доля_з = Xз / X if X else float('nan')
        ис = исход(g['lo'], d)
        con = 'С' if доля_з >= 0.5 else 'не С'
        итог[имя] = (g, d, ис, con, доля_з)
        вывод(f"| {имя}{('' if v is None else f' ({v:g} м/сут)')} | {наш['n']} | {наш['лет']} | {g['GC']:.4f} | {g['lo']:.4f} | {g['hi']:.4f} | {g['повторов']} | {g['ДМ']:.2f} | {g['p']:.4f} | {d:+.4f} | {наш['разрыв']:.4f} | {нотб} | {X} | {I / U:.4f} | {доля_з:.3f} | {дор['доля']:.4f} | {ис} | {con} |")
        tsv.append([имя, '' if v is None else v, наш['n'], наш['лет'], f"{g['GC']:.4f}", f"{g['lo']:.4f}", f"{g['hi']:.4f}", g['повторов'], f"{g['ДМ']:.2f}", f"{g['p']:.4f}", f'{d:+.4f}', f"{наш['разрыв']:.4f}", нотб, X, f'{I / U:.4f}', f'{доля_з:.4f}', f"{дор['доля']:.4f}", ис, con])
    вывод('')
    вывод('П4 (ЗБС с наблюдаемой проходкой): ' + ('признак подтверждён (50 из 373), ячейка считалась' if п4_ok else f"ОСТАНОВ по правилу 4.1 - признак «проходка_м не равна медиане» даёт {флаг_таблица} из {з.height} в таблице CAPEX ППП (в совокупности цепи {флаг_цепь} из {len(ids_цепи & збс)}), а не 50 из 373. Причина: в capex_physical_ПП проходка_м есть ПРОГНОЗ объёмов (capex_exante), у ЗБС {з['проходка_м'].n_unique()} различных значений, подставленной медианы нет. П4 не посчитана, исход «не определён». Справка (не расчёт): в capex_physical.parquet (фактические объёмы) признак даёт {инфо_физ} из {физ.height}, в совокупности цепи {инфо_физ_цепь}."))
    вывод('')
    r1 = рез['П1'][0]
    npv = _цены(r1)
    inc = {True: 0.0, False: 0.0}
    sel = {e19.LINE: [0, 0], 'факт инженеров': [0, 0]}
    for g in r1['отборы']:
        for линия, sign in ((e19.LINE, 1.0), ('факт инженеров', -1.0)):
            ids = g['op_id'][g['отбор'][линия]].tolist()
            sel[линия][0] += sum((i in збс for i in ids))
            sel[линия][1] += len(ids)
            for i in ids:
                inc[i in збс] += sign * npv[i]
    tot = inc[True] + inc[False]
    п3_доля = inc[True] / tot
    вывод(f"П3 (вклад, не цепь): доля ЗБС в приросте NPV отбора над фактом на цепи П1 = {п3_доля:.4f}; ЗБС в отборе нашей линии {sel[e19.LINE][0]} из {sel[e19.LINE][1]} ({sel[e19.LINE][0] / sel[e19.LINE][1]:.4f}), в факте инженеров {sel['факт инженеров'][0]} из {sel['факт инженеров'][1]} ({sel['факт инженеров'][0] / sel['факт инженеров'][1]:.4f}). Это НЕ «GC только ЗБС».")
    вывод('')
    считаемые = ['П1', 'П2', 'П5', 'П7']
    gcs = [итог[k][0]['GC'] for k in считаемые + ['П1']]
    вывод('ИСХОДЫ ПО ЯЧЕЙКАМ: ' + '; '.join((f'{k}: {итог[k][2]}' + (' / С' if итог[k][3] == 'С' else '') for k in считаемые)) + '; П6 = П1; П4: ' + ('см. выше' if п4_ok else 'не определён (ОСТАНОВ признака)') + f"; границы (вне исхода): Г1 {итог['Г1'][2]}, Г2 {итог['Г2'][2]}")
    вывод(f'Размах GC по считаемым ячейкам П1, П2, П5-П7 (П4 нет): от {min(gcs):.4f} до {max(gcs):.4f}.')
    w_в = [k for k in считаемые if итог[k][2] == 'W']
    д_в = [k for k in считаемые if итог[k][2] == 'Д']
    if w_в:
        вывод(f'Чтение 4.6: W в ячейках {w_в}: вывод в них НЕ держится.')
    elif д_в:
        вывод(f'Чтение 4.6: знак держится, уровень сдвигается в ячейках {д_в}.')
    else:
        вывод('Чтение 4.6: во всех считаемых ячейках П1, П2, П5-П7 исход S' + ('; П4 не определена, поэтому формулировка «все ячейки S» относится к считаемым ячейкам и не покрывает П4.' if not п4_ok else '.'))
    вывод('')
    for имя, v in ЯЧЕЙКИ:
        g, d, ис, con, дз = итог[имя]
        якорь(f'ep30 zbs {имя} GC', g['GC'])
        якорь(f'ep30 zbs {имя} GC_lo', g['lo'])
        якорь(f'ep30 zbs {имя} GC_hi', g['hi'])
        якорь(f'ep30 zbs {имя} dGC', d, '+.4f')
        якорь(f'ep30 zbs {имя} доля ЗБС в расхождении с Л1', дз, '.3f')
    якорь('ep30 zbs П3 доля ЗБС в приросте', п3_доля)
    якорь('ep30 zbs доля ЗБС в отборе нашей линии', sel[e19.LINE][0] / sel[e19.LINE][1])
    якорь('ep30 zbs доля ЗБС в факте инженеров', sel['факт инженеров'][0] / sel['факт инженеров'][1])
    якорь('ep30 zbs П4 признак: ЗБС с проходкой не равной медиане, таблица ППП', флаг_таблица, 'd')
    якорь('ep30 zbs размах GC min', min(gcs))
    якорь('ep30 zbs размах GC max', max(gcs))
    OUT_MD.write_text('\n'.join(ПРОЧЬ) + '\n', encoding='utf-8')
    with open(OUT_TSV, 'w', encoding='utf-8', newline='') as f:
        w = csv.writer(f, delimiter='\t', lineterminator='\n')
        w.writerow(['ячейка', 'скорость_м_сут', 'n', 'лет', 'GC', 'GC_lo', 'GC_hi', 'повторов', 'ДМ', 'p', 'dGC_к_П1', 'знаменатель', 'операций_отбора', 'расхождение_с_Л1', 'Жаккар_с_Л1', 'доля_ЗБС_в_расхождении', 'ДОР_Л1', 'исход', 'концентрация'])
        w.writerows(tsv)
    return 0
if __name__ == '__main__':
    sys.exit(main())
