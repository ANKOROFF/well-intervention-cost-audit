    print('\n' + '=' * 78)
    print('ДОЗАМЕР (б). ДИ САМОЙ РАЗНОСТИ NPV. Ведомость 3.106.')
    print('=' * 78)
    print(f'  бутстрэп по годам, перцентильный, повторов {ПОВТОРОВ}, семя {СЕМЯ_ДОЗАМЕРА}; линейка -- наша.')
    print(f"{'разность':26s} {'Δ, млрд':>10s} {'95% ДИ Δ':>21s} {'повт.':>6s} {'ДМ':>7s} {'p':>8s} {'ноль в ДИ':>10s} {'согласие':>9s}")
    разности = [('A − C', 'A', ('Л1 (Бургойн, СЫРАЯ dur)', 'модель отклика на сутки')), ('B − D', 'B', ('Л1 (Бургойн, СЫРАЯ dur)', 'медиана типа на сутки')), ('A − (Л2 × отклик)', 'A', ('Л2 (TDABC, занятость)', 'модель отклика на сутки')), ('B − (Л2 × медиана)', 'B', ('Л2 (TDABC, занятость)', 'медиана типа на сутки'))]
    ди_раз = {}
    несогласий = 0
    for имя, к, ключ in разности:
        наш_ряд = по_годам[КЛЕТКА_ЗАТРАТЫ[к], КЛЕТКА_ЛИНИЯ[к]][0]
