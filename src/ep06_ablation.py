        lo, hi, reps = _ди_суммы(d, rng)
        dm, pv, _ = stats.dm_test(d)
        ноль = lo <= 0.0 <= hi
        согласие = ноль and pv >= 0.05 or (not ноль and pv < 0.05)
        несогласий += not согласие
        ди_раз[имя] = {'Δ': float(d.sum()), 'lo': lo, 'hi': hi, 'ДМ': dm, 'p': pv, 'ноль': ноль, 'повторов': reps}
        print(f"  {имя:24s} {d.sum():10.4f} [{lo:9.4f}, {hi:9.4f}] {reps:6d} {dm:7.2f} {pv:8.4f} {('ДА' if ноль else 'нет'):>10s} {('да' if согласие else 'НЕТ'):>9s}")
