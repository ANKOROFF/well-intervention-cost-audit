def калибровать(база: pl.DataFrame, op_ids: set[int], драйвер: str) -> tuple[float, float]:
    t = база.filter(pl.col('op_id').is_in(list(op_ids)))
    сум_capex = float(t['capex'].sum())
    сум_драйвер = float(t[драйвер].fill_null(0.0).sum())
    return (сум_capex / сум_драйвер, сум_драйвер)

def написать_вариант(база: pl.DataFrame, драйвер: str, ставка: float, путь: pathlib.Path) -> None:
    база.select('op_id', capex=pl.col(драйвер).fill_null(0.0) * ставка, мат_измерены=pl.lit(False)).write_parquet(путь)

def прогон(метка: str, p: Params) -> dict:
    d, руб_т = stats.build(p)
    отб = []
    rows = [r for Y in range(2016, 2025) if (r := stats.year_run(d, руб_т, Y, 1, отборы=отб))]
    df = pl.DataFrame(rows)
    v = {k: df[f'{k}|NPV'].to_numpy() for k in stats.LINES}
    f, o = (v['факт инженеров'], v['оракул по факту'])
    из_ = {}
    for k in stats.LINES:
        gc, lo, hi, reps = stats.bootstrap_gc(v[k], f, o)
        dm, pv, _ = (np.nan, np.nan, 0) if k == 'факт инженеров' else stats.dm_test((v[k] - f) / B)
        из_[k] = {'NPV': float(v[k].sum()) / B, 'GC': gc, 'lo': lo, 'hi': hi, 'повторов': reps, 'ДМ': dm, 'p': pv, 'оп': int(df[f'{k}|оп'].sum()) if k != 'случайный отбор' else -1}
    print(f"\nМОДЕЛЬ ЗАТРАТ {метка}: n = {d.height}, лет {df.height}, цена тонны {руб_т:,.0f} ₽/т, Σcapex {d['capex'].sum() / B:.4f} млрд ₽")
    print(f"{'линия':28s} {'NPV, млрд':>10s} {'GC':>8s} {'95% ДИ GC':>19s} {'ДМ':>7s} {'p':>8s} {'отобр.':>7s}")
    for k in stats.LINES:
        r = из_[k]
        print(f"  {k:26s} {r['NPV']:10.4f} {r['GC']:8.4f} [{r['lo']:8.4f}, {r['hi']:7.4f}] {r['ДМ']:7.2f} {r['p']:8.4f} {r['оп']:7d}")
    print(f'  разрыв «оракул − факт» {(o - f).sum() / B:.4f} млрд ₽ (факт {f.sum() / B:.4f}, оракул {o.sum() / B:.4f}) -- это ЗНАМЕНАТЕЛЬ GC этой модели затрат, и у разных моделей он РАЗНЫЙ (ведомость 3.79)')
    return {'метка': метка, 'n': d.height, 'лет': df.height, 'линии': из_, 'd': d, 'руб_т': руб_т, 'df': df, 'отборы': отб, 'разрыв': float((o - f).sum()) / B, 'факт': float(f.sum()) / B, 'оракул': float(o.sum()) / B}

def линия_л3(рез: dict) -> dict:
    d, руб_т = (рез['d'], рез['руб_т'])
    npv_л3, оп_л3, сутки_л3, емк = ([], [], [], [])
    for Y in range(2016, 2025):
        tr = d.filter(pl.col('год') < Y)
        pool = d.filter(pl.col('год') == Y)
        fact = (pool['год'] == Y).to_numpy()
        if tr.height < 300 or fact.sum() < 20:
            continue
        npv = pool['npv'].to_numpy()
        capex = pool['capex'].to_numpy()
        dur = pool['бригадо_сутки'].to_numpy().clip(1, 400)
        budget, cap = (capex[fact].sum(), dur[fact].sum())
        sel = stats.greedy(npv / np.clip(capex, 1.0, None), capex, dur, budget, np.inf)
        npv_л3.append(float(npv[sel].sum()))
        оп_л3.append(int(sel.sum()))
        сутки_л3.append(float(dur[sel].sum()))
        емк.append(float(cap))
    v = np.array(npv_л3)
    f = рез['df']['факт инженеров|NPV'].to_numpy()
    o = рез['df']['оракул по факту|NPV'].to_numpy()
    gc, lo, hi, reps = stats.bootstrap_gc(v, f, o)
    dm, pv, _ = stats.dm_test((v - f) / B)
    перебор = sum((с > е for с, е in zip(сутки_л3, емк)))
    print(f'\nЛ3 индекс рентабельности (NPV на рубль CAPEX, ОДНО ограничение):')
    print(f'  NPV {v.sum() / B:.4f} млрд ₽, GC {gc:.4f} [{lo:.4f}, {hi:.4f}], ДМ {dm:.2f}, p = {pv:.4f}, отобрано {sum(оп_л3)}')
    print(f'  Л3 превысила фактическую ёмкость бригад в {перебор} годах из {len(емк)}: отношение бригадо-суток к ёмкости {sum(сутки_л3) / sum(емк):.4f}')
    return {'NPV': v.sum() / B, 'GC': gc, 'lo': lo, 'hi': hi, 'ДМ': dm, 'p': pv, 'оп': sum(оп_л3), 'перебор': перебор, 'лет': len(емк), 'отн_емк': sum(сутки_л3) / sum(емк)}

def не_охвачено(наш: dict, варианты: dict, л3: dict) -> None:
    print('\n=== ЧТО ПРАВИЛОМ Э6.1 НЕ ОХВАЧЕНО (измерено, НЕ вердикт) ===')
    print('\nМЕХАНИЗМ: у каждой модели затрат СВОЙ базис и СВОЙ потолок.')
    print(f"{'модель затрат':28s} {'факт, млрд':>11s} {'оракул, млрд':>13s} {'разрыв, млрд':>13s}")
    for r in [наш] + list(варианты.values()):
        print(f"  {r['метка']:26s} {r['факт']:11.4f} {r['оракул']:13.4f} {r['разрыв']:13.4f}")
    print('  Доля закрытого разрыва РАСТЁТ, когда разрыв растёт не от того, что программа\n  инженеров стала хуже, а от того, что модель затрат оценила её иначе. GC\n  поэтому НЕ является мерилом качества модели затрат, и правило 3.81 сравнивало\n  величины, несравнимость которых строка 3.79 назвала заранее.')
    наш_npv = {}
    for г in наш['отборы']:
        наш_npv.update(dict(zip(г['op_id'].tolist(), г['npv'].tolist())))
    print('\nСОСТАВ ПРОГРАММЫ: совпадение отобранных множеств между клетками.')
    print('  Это прямой ответ на вопрос «меняет ли модель затрат СОСТАВ», и он НЕ требует\n  сравнения долей с разными знаменателями.')
    пары = [('A против C', 'модель отклика на сутки', 'Л1 (Бургойн, СЫРАЯ dur)'), ('B против D', 'медиана типа на сутки', 'Л1 (Бургойн, СЫРАЯ dur)'), ('A против Л2', 'модель отклика на сутки', 'Л2 (TDABC, занятость)')]
    for имя, линия, вар in пары:
        общ = разн = 0
        for г1, г2 in zip(наш['отборы'], варианты[вар]['отборы']):
            assert (г1['op_id'] == г2['op_id']).all(), 'пулы года разошлись'
            s1, s2 = (г1['отбор'][линия], г2['отбор'][линия])
            общ += int((s1 & s2).sum())
            разн += int((s1 ^ s2).sum())
        жак = общ / (общ + разн) if общ + разн else float('nan')
        _СОСТАВ[имя] = (общ, разн, жак)
        print(f'  {имя:12s} линия «{линия}»: совпало {общ}, разошлось {разн}, Жаккар {жак:.4f}')
    print('\nОДНА ЛИНЕЙКА: отбор, сделанный при другой модели затрат, оценённый НАШИМ NPV.')
    print('  Сравнение законно, потому что мерило одно. Осуществимость при НАШЕМ бюджете\n  проверяется отдельно: отбор, сделанный при другом бюджете, мог в наш не влезть.')
    print('  Разность проверяется тестом Дибольда-Мариано на ПОГОДОВЫХ разностях, а не\n  предъявляется точечной суммой: девять лет -- малая выборка.')
    print(f"{'что оценивается':34s} {'NPV нашим, млрд':>16s} {'влез в наш':>12s} {'Δ к нашему':>11s} {'ДМ':>7s} {'p':>8s}")
    по_годам = {}
    for вар in ['Л1 (Бургойн, СЫРАЯ dur)', 'Л2 (TDABC, занятость)']:
        for линия in ('модель отклика на сутки', 'медиана типа на сутки'):
            ряд, влез = ([], 0)
            for г1, г2 in zip(наш['отборы'], варианты[вар]['отборы']):
                s = г2['отбор'][линия]
                ряд.append(float(np.array([наш_npv[i] for i in г2['op_id'][s].tolist()]).sum()))
                влез += int(г1['capex'][s].sum() <= г1['бюджет'] and г1['dur'][s].sum() <= г1['ёмкость'])
            по_годам[вар, линия] = (np.array(ряд), влез)
    for линия in ('модель отклика на сутки', 'медиана типа на сутки'):
        наш_ряд = np.array([float(г['npv'][г['отбор'][линия]].sum()) for г in наш['отборы']])
        по_годам['НАША (физическая Ш4b)', линия] = (наш_ряд, len(наш['отборы']))
    for (вар, линия), (ряд, влез) in по_годам.items():
        наш_ряд = по_годам['НАША (физическая Ш4b)', линия][0]
        if вар.startswith('НАША'):
            дм = пв = float('nan')
            d = 0.0
        else:
            дм, пв, _ = stats.dm_test((наш_ряд - ряд) / B)
            d = float((наш_ряд - ряд).sum()) / B
        имя = f'{вар.split()[0]} x {линия.split()[0]}'
        _ЛИНЕЙКА[имя] = (float(ряд.sum()) / B, влез, d, дм, пв)
        print(f"  {имя:32s} {ряд.sum() / B:16.4f} {влез:7d} из {len(наш['отборы'])} {d:+11.4f} {дм:7.2f} {пв:8.4f}")
    print('  Знак Δ положителен, когда НАШ отбор лучше при одном мериле. Это ИЗМЕРЕННЫЙ\n  факт, а НЕ вердикт по правилу Э6.1: правило объявило предметом сравнение GC,\n  и его исход назван ниже отдельно.')
    совп = разл = 0
    for г in наш['отборы']:
        npv, capex, dur = (г['npv'], г['capex'], г['dur'])
        s3 = stats.greedy(npv / np.clip(capex, 1.0, None), capex, dur, г['бюджет'], np.inf)
        so = г['отбор']['оракул по факту']
        совп += int((s3 == so).all())
        разл += int((s3 ^ so).sum())
    _Л3.update({'совп': совп, 'разл': разл, 'лет': len(наш['отборы'])})
    print(f"\nЛ3 ПРОТИВ ОРАКУЛА: отборы совпали поэлементно в {совп} годах из {len(наш['отборы'])}, расхождений {разл} операций.")
    print(f"  Л3 дала GC {л3['GC']:.4f} НЕ потому, что индекс рентабельности хорош, а потому,\n  что ограничения НЕ СВЯЗЫВАЮТ (отношение бригадо-суток к ёмкости {л3['отн_емк']:.4f},\n  превышений ёмкости {л3['перебор']} из {л3['лет']}): задача вырождается в «взять всё прибыльное»,\n  и оба правила берут множество {{npv > 0}} -- тот же механизм, что в строке 3.48.")
    print('  Поэтому Л3 на ЭТОЙ постановке как линия-конкурент НЕИНФОРМАТИВНА, и подавать\n  её GC как результат было бы ложью о том, что измерено.')
    return (по_годам, наш_npv)
