    цены_л1 = _цены(л1)
    f_наш = наш['df']['факт инженеров|NPV'].to_numpy()
    o_наш = наш['df']['оракул по факту|NPV'].to_numpy()
    f_л1 = л1['df']['факт инженеров|NPV'].to_numpy()
    o_л1 = л1['df']['оракул по факту|NPV'].to_numpy()
    D_наш = float((o_наш - f_наш).sum())
    D_л1 = float((o_л1 - f_л1).sum())
    print('\n' + '=' * 78)
    print('ДОЗАМЕР (а). ДОР -- ДОЛЯ ОБЩЕГО РАЗРЫВА. Ведомость 3.100-3.105.')
    print('=' * 78)
    print(f'  знаменатель ОДИН на все клетки: разрыв нашей модели {D_наш / B:.4f} млрд ₽ (строка 3.94)')
