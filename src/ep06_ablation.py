    совп_дм = sum((abs(d['ДМ_npv'] - d['ДМ_дор']) < 1e-09 * max(abs(d['ДМ_npv']), 1.0) and abs(d['p'] - d['p_дор']) < 1e-09 * max(abs(d['p']), 1.0) for d in дор.values()))
    print(f'  ТОЖДЕСТВО 3.103: ДМ и p по NPV и по ДОР совпали в {совп_дм} клетках из 4 -- нормировка на константу статистику не меняет.')
    тавт = abs(дор['A']['ДОР'] - клетки['A']['GC']) < 1e-09 * max(abs(дор['A']['ДОР']), 1.0)
    print(f"  ТАВТОЛОГИЯ 3.101: ДОР(A) = {дор['A']['ДОР']:.4f} против GC(A) = {клетки['A']['GC']:.4f} -> {('тождественны, как объявлено' if тавт else 'РАСХОЖДЕНИЕ')}. Это не сверка.")
    print(f'\n  ОБЯЗАТЕЛЬНЫЙ СИММЕТРИЧНЫЙ ЗАМЕР (3.105): те же четыре отбора, линейка Л1,\n  знаменатель Л1 {D_л1 / B:.4f} млрд ₽. Нужен затем, чтобы исход Д1 нельзя было\n  прочитать как «наша модель затрат вернее»: ДОР по нашей линейке благоволит\n  отбору под эту же линейку.')
    print(f"{'клетка':7s} {'ДОР(Л1)':>9s} {'95% ДИ':>19s} {'NPV линейкой Л1':>16s}")
    дор_л1 = {}
    for к in ('A', 'B', 'C', 'D'):
        источник = наш if КЛЕТКА_ЗАТРАТЫ[к].startswith('НАША') else л1
