def _ряд_линейкой(отборы_клетки, цены: dict, линия: str) -> np.ndarray:
    return np.array([float(np.array([цены[i] for i in г['op_id'][г['отбор'][линия]].tolist()]).sum()) for г in отборы_клетки])

def _цены(рез: dict) -> dict:
    ц = {}
    for г in рез['отборы']:
        ц.update(dict(zip(г['op_id'].tolist(), г['npv'].tolist())))
    return ц

def _ди_суммы(ряд: np.ndarray, rng) -> tuple[float, float, int]:
    n = len(ряд)
    s = np.array([ряд[rng.integers(0, n, n)].sum() for _ in range(ПОВТОРОВ)])
    return (float(np.percentile(s, 2.5)), float(np.percentile(s, 97.5)), len(s))

