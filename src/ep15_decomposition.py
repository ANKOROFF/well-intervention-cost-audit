from __future__ import annotations
import pathlib
import sys
import tempfile
import numpy as np
import polars as pl
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import stats
from ep06_ablation import БАЗА, N_ОБЪЯВЛЕНО, калибровать, написать_вариант
from npv import Params
B = 1000000000.0
ПОРОГ_ПП = 0.5
МНОЖИТЕЛЬ = 3.0
ПОВТОРОВ = 2000
СЕМЯ = 20261003
НЕВЯЗКА_МЛРД = 1e-06
ОЖ = {'ДОР A': 0.2938, 'ΔK': float('nan'), 'оракул': float('nan'), 'факт': float('nan')}
ГОДЫ = range(2016, 2025)

def _прогон(p: Params, span: int) -> dict:
    d, руб_т = stats.build(p)
    отб: list = []
    for Y in ГОДЫ:
        stats.year_run(d, руб_т, Y, span, отборы=отб)
    for г in отб:
        npv, cx, du = (г['npv'], г['capex'], г['dur'])
        b, c = (г['бюджет'], г['ёмкость'])
        г['отбор']['И абс'] = stats.greedy(npv, cx, du, b, c)
        г['отбор']['И сут'] = stats.greedy(npv / du, cx, du, b, c)
    цены = {}
    for г in отб:
        цены.update(dict(zip(г['op_id'].tolist(), г['npv'].tolist())))
    return {'n': d.height, 'отб': отб, 'цены': цены}

def ряд(рез: dict, цены: dict, линия: str) -> np.ndarray:
    return np.array([float(sum((цены[i] for i in г['op_id'][г['отбор'][линия]].tolist()))) for г in рез['отб']])

def бутстрэп_суммы(x: np.ndarray, rng) -> tuple[float, float]:
    n = len(x)
    s = np.array([x[rng.integers(0, n, n)].sum() for _ in range(ПОВТОРОВ)])
    return (float(np.percentile(s, 2.5)), float(np.percentile(s, 97.5)))

def пп(x: float, д: float) -> float:
    return 100.0 * x / д

def якорь(имя: str, знач, ф: str='.4f') -> None:
    print(f'ЯКОРЬ {имя} = {format(знач, ф)}')

def исход_величины(a: float, b: float) -> tuple[str, str]:
    выше_a, выше_b = (a >= ПОРОГ_ПП, b >= ПОРОГ_ПП)
    if not выше_a and (not выше_b):
        return ('О0', 'оба вклада неразличимы от нуля: вопрос Keisler на этих данных не разрешён')
    if выше_a != выше_b:
        return ('О1', 'различим только вклад ' + ('правила' if выше_a else 'затрат') + ', второй не отличим от нуля')
    бол, мен = (max(a, b), min(a, b))
    if бол >= МНОЖИТЕЛЬ * мен:
        return ('О2', 'вклад ' + ('правила' if a > b else 'затрат') + f' много больше (в {бол / мен:.2f} раза)')
    return ('О3', f'вклады сравнимы (отношение {бол / мен:.2f}), порядок не заявляется')

def постановка(метка: str, нашa: dict, л1: dict, вердикт: bool) -> dict:
    ц_н, ц_л = (нашa['цены'], л1['цены'])
    print(f"\n{'=' * 78}\n{метка}\n{'=' * 78}")
    for r, нм in ((нашa, 'наша'), (л1, 'Л1')):
        print(f"  n {нм} = {r['n']}, лет {len(r['отб'])}")
    for г1, г2 in zip(нашa['отб'], л1['отб']):
        assert np.array_equal(г1['op_id'], г2['op_id']), 'op_id двух моделей затрат разошлись'
    F = ряд(нашa, ц_н, 'факт инженеров')
    O = ряд(нашa, ц_н, 'оракул по факту')
    V = {('абс', 'Л1', 'М'): ряд(л1, ц_н, 'предсказ. абсолютный NPV'), ('сут', 'Л1', 'М'): ряд(л1, ц_н, 'модель отклика на сутки'), ('абс', 'Н', 'М'): ряд(нашa, ц_н, 'предсказ. абсолютный NPV'), ('сут', 'Н', 'М'): ряд(нашa, ц_н, 'модель отклика на сутки'), ('абс', 'Н', 'И'): ряд(нашa, ц_н, 'И абс'), ('сут', 'Н', 'И'): ряд(нашa, ц_н, 'И сут'), ('абс', 'Л1', 'И'): ряд(л1, ц_н, 'И абс'), ('сут', 'Л1', 'И'): ряд(л1, ц_н, 'И сут')}
    Д = (O - F).sum()
    print(f'\nКУБ ОТБОРОВ, нашей линейкой, млрд ₽ (общий знаменатель Д = {Д / B:.4f}):')
    print(f'  факт инженеров {F.sum() / B:10.4f}   оракул {O.sum() / B:10.4f}')
    for k, v in V.items():
        print(f'  ({k[0]:>3}, {k[1]:>2}, {k[2]})        {v.sum() / B:10.4f}   ДОР {(v - F).sum() / Д:8.4f}')
    Z = V['абс', 'Л1', 'М'] - F
    dR = V['сут', 'Л1', 'М'] - V['абс', 'Л1', 'М']
    dK = V['сут', 'Н', 'М'] - V['сут', 'Л1', 'М']
    dE = V['сут', 'Н', 'И'] - V['сут', 'Н', 'М']
    dh = O - V['сут', 'Н', 'И']
    части = {'Z': Z, 'ΔR': dR, 'ΔK': dK, 'ΔE': dE, 'Δh': dh}
    сумма = sum(части.values())
    невязка_год = np.abs(сумма - (O - F))
    невязка = abs(float(сумма.sum() - (O - F).sum()))
    print('\nТАБЛИЦА ДВУХ РАЗЛОЖЕНИЙ (цепочка 3.143), нашей линейкой:')
    print('| часть | что это | млрд ₽ | п.п. Д | ДМ | p | 95% ДИ, млрд ₽ |')
    print('|---|---|---:|---:|---:|---:|---|')
    опис = {'Z': 'закрыто конвенциональным конвейером (абс, Л1, М)', 'ΔR': 'вклад правила ранжирования (абс → сут)', 'ΔK': 'вклад точности затрат (Л1 → Н)', 'ΔE': 'вклад точности оценки эффекта (М → И)', 'Δh': 'зазор жадного до точного оптимума'}
    rng = np.random.default_rng(СЕМЯ)
    стат = {}
    for к, x in части.items():
        dm, p, _ = stats.dm_test(x / B)
        lo, hi = бутстрэп_суммы(x, rng)
        стат[к] = (dm, p, lo, hi)
        dms = '—' if dm != dm else f'{dm:.2f}'
        ps = '—' if p != p else f'{p:.4f}'
        print(f'| **{к}** | {опис[к]} | **{x.sum() / B:.4f}** | **{пп(x.sum(), Д):.2f}** | {dms} | {ps} | [{lo / B:.4f}, {hi / B:.4f}] |')
    print(f'| **Σ** | сумма пяти частей | **{сумма.sum() / B:.4f}** | **{пп(сумма.sum(), Д):.2f}** | | | |')
    print(f'| **Д** | общий разрыв «оракул − факт» | **{Д / B:.4f}** | **100.00** | | | |')
    print('\nПРОВЕРКА ЗАМЫКАНИЯ (ведомость 3.144):')
    ок_а = невязка / B <= НЕВЯЗКА_МЛРД and float(невязка_год.max()) / B <= НЕВЯЗКА_МЛРД
    print(f"  (а) невязка суммы частей против Д: в сумме {невязка / B:.2e} млрд ₽, максимум по годам {float(невязка_год.max()) / B:.2e} -> {('ВЫПОЛНЕНО' if ок_а else 'ПРОВАЛ')}")
    ддр_A = (V['сут', 'Н', 'М'] - F).sum() / Д
    z_rk = (Z + dR + dK).sum() / Д
    ок_б = ок_в = ок_г = True
    if вердикт:
        ок_б = round(z_rk, 4) == ОЖ['ДОР A']
        print(f"  (б) Z + ΔR + ΔK = {z_rk:.4f} Д против ДОР(A) = GC(A) = {ОЖ['ДОР A']:.4f} -> {('ВЫПОЛНЕНО' if ок_б else 'ПРОВАЛ')}")
        ок_в = round(dK.sum() / B, 4) == ОЖ['ΔK']
        print(f"  (в) ΔK = {dK.sum() / B:.4f} млрд ₽ против <withheld> (строка 3.96) -> {('ВЫПОЛНЕНО' if ок_в else 'ПРОВАЛ')}")
        ок_г = round(O.sum() / B, 4) == ОЖ['оракул'] and round(F.sum() / B, 4) == ОЖ['факт']
        print(f"  (г) оракул {O.sum() / B:.4f} и факт {F.sum() / B:.4f} млрд ₽ против <withheld> и <withheld> (строка 3.94) -> {('ВЫПОЛНЕНО' if ок_г else 'ПРОВАЛ')}")
    else:
        print('  (б)-(г) к расширению НЕ применимы: ожидаемые значения строк 3.87, 3.94, 3.96 есть значения пула года Y, у пула Y..Y+2 они другие по построению')
    замкнуто = bool(ок_а and ок_б and ок_в and ок_г)
    dK2 = V['абс', 'Н', 'М'] - V['абс', 'Л1', 'М']
    dR2 = V['сут', 'Н', 'М'] - V['абс', 'Н', 'М']
    I = (dR2 - dR).sum()
    print(f'\nПОРЯДОК ЦЕПОЧКИ (ведомость 3.145), п.п. Д:')
    print(f'  правило -> затраты: ΔR {пп(dR.sum(), Д):+.2f}, ΔK {пп(dK.sum(), Д):+.2f}')
    print(f'  затраты -> правило: ΔK′ {пп(dK2.sum(), Д):+.2f}, ΔR′ {пп(dR2.sum(), Д):+.2f}')
    print(f'  взаимодействие I = ΔR′ − ΔR = {пп(I, Д):+.2f} п.п. Д (и ΔK − ΔK′ = {пп((dK - dK2).sum(), Д):+.2f})')
    аддитивно = abs(пп(I, Д)) < ПОРОГ_ПП
    print(f"  {('АДДИТИВНО в пределах порога 0.5 п.п.' if аддитивно else 'НЕ АДДИТИВНО: вклады зависят от порядка, доли заявлять нельзя; заявляется таблица 2x2')}")
    gc_абс = (V['абс', 'Н', 'И'] - F).sum() / Д
    gc_сут = (V['сут', 'Н', 'И'] - F).sum() / Д
    print(f'\nАНАЛОГ ЧИСЛА 0.903 при истинной информации (ведомость 3.150), доля Д:')
    print(f'  жадный по абсолютному NPV {gc_абс:.4f}, жадный на бригадо-сутки {gc_сут:.4f}, оракул 1.0000; разность {100 * (gc_сут - gc_абс):.2f} п.п.')
    стат_ис = V['сут', 'Н', 'И'] - V['абс', 'Н', 'И']
    print(f'  правило при истинной информации, нашей линейкой: {стат_ис.sum() / B:.4f} млрд ₽ = {пп(стат_ис.sum(), Д):.2f} п.п. Д')
    print(f"  совпадение отборов абс и сут (Н, М) по годам: {sum((bool((a['отбор']['предсказ. абсолютный NPV'] == a['отбор']['модель отклика на сутки']).all()) for a in нашa['отб']))} из {len(нашa['отб'])}; (Л1, М): {sum((bool((a['отбор']['предсказ. абсолютный NPV'] == a['отбор']['модель отклика на сутки']).all()) for a in л1['отб']))} из {len(л1['отб'])}")
    FЛ = ряд(л1, ц_л, 'факт инженеров')
    OЛ = ряд(л1, ц_л, 'оракул по факту')
    ДЛ = (OЛ - FЛ).sum()
    dR_л = ряд(л1, ц_л, 'модель отклика на сутки') - ряд(л1, ц_л, 'предсказ. абсолютный NPV')
    dK_л = ряд(нашa, ц_л, 'модель отклика на сутки') - ряд(л1, ц_л, 'модель отклика на сутки')
    print(f'\nСИММЕТРИЧНЫЙ ЗАМЕР линейкой Л1 (ведомость 3.148), Д_Л1 = {ДЛ / B:.4f} млрд ₽:')
    print(f'  ΔR по линейке Л1: {dR_л.sum() / B:+.4f} млрд ₽ = {пп(dR_л.sum(), ДЛ):+.2f} п.п. Д_Л1')
    print(f'  ΔK по линейке Л1: {dK_л.sum() / B:+.4f} млрд ₽ = {пп(dK_л.sum(), ДЛ):+.2f} п.п. Д_Л1')
    знак_обратен = (dK.sum() > 0) != (dK_л.sum() > 0)
    print(f"  знак вклада затрат {('ОБРАТЕН' if знак_обратен else 'тот же')} по линейке Л1 ({('«по нашей линейке» обязательно, верность модели затрат не разрешена' if знак_обратен else 'ограничение снято')})")
    a, b_ = (abs(пп(dR.sum(), Д)), abs(пп(dK.sum(), Д)))
    исход, текст = исход_величины(a, b_)
    e = abs(пп(dE.sum(), Д))
    е_исход = 'Е1' if e >= max(a, b_) else 'Е0'
    р_слаб = [к for к, v in (('правила', стат['ΔR']), ('затрат', стат['ΔK'])) if not (v[1] == v[1] and v[1] < 0.05)]
    print(f'\nВЕРДИКТ ПО ПРАВИЛУ (ведомость 3.146, 3.149): a = |ΔR| = {a:.2f} п.п., b = |ΔK| = {b_:.2f} п.п., |ΔE| = {e:.2f} п.п.')
    print(f'  НАСТУПИЛ ИСХОД {исход}: {текст}.')
    print(f"  остаток: исход {е_исход} ({('оценка эффекта главный источник незакрытого разрыва' if е_исход == 'Е1' else 'заявление об оценке эффекта не делается')}); ΔR + ΔK объясняют {пп((dR + dK).sum(), Д):+.2f} п.п. Д")
    print(f"  части без различимой опоры (p ≥ 0.05 либо тест неприменим): {(', '.join(р_слаб) if р_слаб else 'нет')}")
    return {'Д': Д, 'F': F, 'O': O, 'части': части, 'стат': стат, 'замкнуто': замкнуто, 'I': I, 'аддитивно': аддитивно, 'исход': исход, 'е_исход': е_исход, 'dK2': dK2, 'dR2': dR2, 'gc_абс': gc_абс, 'gc_сут': gc_сут, 'ДЛ': ДЛ, 'dR_л': dR_л, 'dK_л': dK_л, 'невязка': невязка, 'невязка_год': float(невязка_год.max()), 'V': V, 'знак_обратен': знак_обратен, 'zrk': float(z_rk), 'ок': tuple((bool(x) for x in (ок_а, ок_б, ок_в, ок_г))), 'FЛ': FЛ, 'OЛ': OЛ}

def сводка(м: str, р: dict) -> None:
    Д = р['Д']
    print(f'\n=== СВОДКА ДЛЯ МАНИФЕСТА, {м} (одно число -- одна строка) ===')
    якорь(f'{м} факт млрд', р['F'].sum() / B)
    якорь(f'{м} оракул млрд', р['O'].sum() / B)
    якорь(f'{м} общий разрыв млрд', Д / B)
    for к, x in р['части'].items():
        якорь(f'{м} часть {к} млрд', x.sum() / B)
        якорь(f'{м} часть {к} пп', пп(x.sum(), Д), '.2f')
    for к in ('ΔR', 'ΔK'):
        dm, p, lo, hi = р['стат'][к]
        if dm == dm:
            якорь(f'{м} {к} ДМ', dm, '.2f')
            якорь(f'{м} {к} p', p)
        якорь(f'{м} {к} ДИ низ млрд', lo / B)
        якорь(f'{м} {к} ДИ верх млрд', hi / B)
    for k, v in р['V'].items():
        якорь(f'{м} куб {k[0]} {k[1]} {k[2]} млрд', v.sum() / B)
    якорь(f'{м} Z плюс ΔR плюс ΔK доля Д', р['zrk'])
    якорь(f'{м} сумма частей пп', пп(sum((x.sum() for x in р['части'].values())), Д), '.2f')
    якорь(f'{м} невязка суммарная млрд', р['невязка'] / B)
    якорь(f'{м} невязка максимум по годам млрд', р['невязка_год'] / B)
    якорь(f'{м} взаимодействие пп', пп(р['I'], Д), '.2f')
    якорь(f'{м} ΔR обратный порядок пп', пп(р['dR2'].sum(), Д), '.2f')
    якорь(f'{м} ΔK обратный порядок пп', пп(р['dK2'].sum(), Д), '.2f')
    якорь(f'{м} GC правила, жадный абс, истинная информация', р['gc_абс'])
    якорь(f'{м} GC правила, жадный сут, истинная информация', р['gc_сут'])
    якорь(f'{м} знаменатель Л1 млрд', р['ДЛ'] / B)
    якорь(f'{м} ΔR линейка Л1 пп', пп(р['dR_л'].sum(), р['ДЛ']), '.2f')
    якорь(f'{м} ΔK линейка Л1 пп', пп(р['dK_л'].sum(), р['ДЛ']), '.2f')
    якорь(f'{м} номер исхода по величине', int(р['исход'][1:]), 'd')
    якорь(f'{м} номер исхода по остатку', int(р['е_исход'][1:]), 'd')
    якорь(f'{м} замыкание выполнено, 1 да 0 нет', int(р['замкнуто']), 'd')
    якорь(f'{м} аддитивность, 1 да 0 нет', int(р['аддитивно']), 'd')

def главная() -> int:
    база = pl.read_parquet(БАЗА)
    врем = pathlib.Path(tempfile.mkdtemp(prefix='ep15_'))
    нашa1 = _прогон(Params(), 1)
    if нашa1['n'] != N_ОБЪЯВЛЕНО:
        print(f"ОСТАНОВ по правилу 3.140: n = {нашa1['n']} против {N_ОБЪЯВЛЕНО}.")
        return 1
    op_ids = set(stats.build(Params())[0]['op_id'].to_list())
    ставка, сум = калибровать(база, op_ids, 'dur')
    путь = врем / 'dur.parquet'
    написать_вариант(база, 'dur', ставка, путь)
    p_л1 = Params(capex_source=str(путь))
    л11 = _прогон(p_л1, 1)
    if л11['n'] != N_ОБЪЯВЛЕНО:
        print(f"ОСТАНОВ по правилу 3.140: n(Л1) = {л11['n']} против {N_ОБЪЯВЛЕНО}.")
        return 1
    print(f'ставка Л1 {ставка:,.0f} ₽/сут, сумма драйвера {сум:,.1f} сут (строка 3.92: <withheld> и 123 046.0)')
    р1 = постановка('ОСНОВНАЯ ПОСТАНОВКА: пул года Y, 5 871 операция, девять лет', нашa1, л11, True)
    сводка('п1', р1)
    нашa3 = _прогон(Params(), 3)
    л13 = _прогон(p_л1, 3)
    р3 = постановка('РАСШИРЕНИЕ: пул Y..Y+2 (заднее знание о кандидатах), В ВЕРДИКТ НЕ ВХОДИТ', нашa3, л13, False)
    сводка('п3', р3)
    print('\n=== ИТОГ Э15 ===')
    print(f"  замыкание основной постановки: {('ВЫПОЛНЕНО' if р1['замкнуто'] else 'ПРОВАЛ')} (а, б, в, г = {р1['ок']})")
    print(f"  исход по величине: {р1['исход']}; по остатку: {р1['е_исход']}; аддитивность по существу: {('да' if р1['аддитивно'] else 'нет')}")
    return 0 if р1['замкнуто'] else 1
if __name__ == '__main__':
    sys.exit(главная())
