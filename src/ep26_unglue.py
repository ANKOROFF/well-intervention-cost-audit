def доли_capex(база: pl.DataFrame, op_ids: list[int]) -> dict:
    t = база.filter(pl.col('op_id').is_in(op_ids))
    всего = float(t['capex'].sum())
    части = ['c_крс', 'c_флот_грп', 'c_станок', 'c_моб', 'c_время', 'c_материалы_исп']
    д = {к: float(t[к].sum()) / всего for к in части}
    д['сверх занятости'] = 1.0 - д['c_крс']
    return д

def ди_суммы(ряд: np.ndarray, rng) -> tuple[float, float]:
    n = len(ряд)
    s = np.array([ряд[rng.integers(0, n, n)].sum() for _ in range(ПОВТОРОВ_ДИ)])
    return (float(np.percentile(s, 2.5)), float(np.percentile(s, 97.5)))

def состав_пары(первый: dict, второй: dict, линия: str, цены_наш: dict) -> dict:
    г = группы(первый, второй, линия)
    оп_1, оп_2 = (г['op_наш'], г['op_л1'])
    общ = 0
    for г1, г2 in zip(первый['отборы'], второй['отборы']):
        s1, s2 = (г1['отбор'][линия], г2['отбор'][линия])
        общ += int((s1 & s2).sum())
    разн = len(оп_1) + len(оп_2)
    жак = общ / (общ + разн) if общ + разн else float('nan')
    брутто_1 = sum((цены_наш[o] for o in оп_1)) / B
    брутто_2 = sum((цены_наш[o] for o in оп_2)) / B
    return {'совпало': общ, 'разошлось': разн, 'Жаккар': жак, 'оп_1': len(оп_1), 'оп_2': len(оп_2), 'брутто_1': брутто_1, 'брутто_2': брутто_2, 'брутто': abs(брутто_1) + abs(брутто_2), 'сальдо': брутто_1 - брутто_2, 'множество_1': оп_1, 'множество_2': оп_2}

def пи_отношения(ро: np.ndarray, инд: dict, оп_1: list, оп_2: list) -> dict:
    i1 = np.array([инд[o] for o in оп_1], dtype=int) if оп_1 else np.array([], int)
    i2 = np.array([инд[o] for o in оп_2], dtype=int) if оп_2 else np.array([], int)
    за_2 = сторона(ро, 1.0, 'низ')
    за_1 = сторона(ро, 1.0, 'верх')
    верно_2 = int(за_2[i2].sum()) if len(i2) else 0
    верно_1 = int(за_1[i1].sum()) if len(i1) else 0
    всего = len(оп_1) + len(оп_2)
    return {'пи': (верно_1 + верно_2) / всего if всего else float('nan'), 'верно_1': верно_1, 'верно_2': верно_2, 'всего': всего}

def сошлось(получено: float, ожидано: float, знаков: int) -> bool:
    return round(получено, знаков) == round(ожидано, знаков)

