def norm_well(col):
    c = col.cast(pl.Utf8).str.strip_chars().str.to_uppercase()
    for a, b in CYR2LAT:
        c = c.str.replace_all(a, b, literal=True)
    return c.str.replace_all('\\s+', '')

def _чис(имя: str):
    return pl.col(имя).cast(pl.Utf8).str.replace_all(',', '.').cast(pl.Float64, strict=False)

def глубины(ev: pl.DataFrame) -> pl.DataFrame:
    пф = pl.read_parquet(cfg.data('parquet/source_perforation.parquet')).select(wr=norm_well(pl.col('SRC_WELL_NAME')), кровля=_чис('Глубина кровли'), дата=pl.col('Дата').cast(pl.Utf8).str.to_datetime(strict=False).dt.date()).drop_nulls(['кровля', 'дата'])
    пары = ev.select('op_id', 'beg', wr=norm_well(pl.col('well_raw'))).join(пф, on='wr', how='inner').filter(pl.col('дата') < pl.col('beg'))
    г = пары.group_by('op_id').agg(глубина_м=pl.col('кровля').median(), перф_записей=pl.len())
    print(f'глубина ИЗМЕРЕНА (перфорация строго до начала операции) у {г.height} из {ev.height} операций двух типов')
    q = г['глубина_м']
    print(f'  квартили глубины {q.quantile(0.25):.0f} / {q.median():.0f} / {q.quantile(0.75):.0f} м; размах {q.min():.0f}..{q.max():.0f} м')
    _ЗАМЕР.update(глубина_измерена=г.height, глубина_q25=q.quantile(0.25), глубина_мед=q.median(), глубина_q75=q.quantile(0.75), глубина_мин=q.min(), глубина_макс=q.max())
    return г

def диаметры(ev: pl.DataFrame) -> pl.DataFrame:
    к = pl.read_parquet(cfg.data('parquet/konstrukciya.parquet')).filter(pl.col('Тип колонны').cast(pl.Utf8).str.strip_chars() == 'э/к').select(wr=norm_well(pl.col('SRC_WELL_NAME')), d=_чис('Диаметр внутренний, мм')).filter(pl.col('d') > 50.0)
    мода = к.group_by(['wr', 'd']).len().sort(['wr', 'len', 'd'], descending=[False, True, True]).group_by('wr').first().select('wr', диаметр_мм='d')
    д = ev.select('op_id', wr=norm_well(pl.col('well_raw'))).join(мода, on='wr', how='left').select('op_id', 'диаметр_мм')
    есть = int(д['диаметр_мм'].is_not_null().sum())
    print(f'диаметр колонны измерен у {есть} из {ev.height}; распределение (шт): ' + ', '.join((f'{r[0]:.1f}: {r[1]}' for r in д['диаметр_мм'].value_counts(sort=True).head(6).iter_rows() if r[0] is not None)))
    k = д.with_columns(K=pl.col('диаметр_мм').map_elements(nv.k_колонна, return_dtype=pl.Float64).fill_null(1.0))
    print(f"  К = 1.3 применена к {int((k['K'] > 1.0).sum())} операциям (диаметр 168 мм и больше), К = 1.0 -- к {int((k['K'] == 1.0).sum())}, из них с НЕИЗВЕСТНЫМ диаметром {int(k['диаметр_мм'].is_null().sum())}")
    _ЗАМЕР.update(k_повышена=int((k['K'] > 1.0).sum()), k_базис=int((k['K'] == 1.0).sum()), диаметр_неизвестен=int(k['диаметр_мм'].is_null().sum()))
    return k

def труб(глубина_м: float, длина_трубы_м: float) -> int:
    return int(math.ceil(глубина_м / длина_трубы_м))

def норматив_ч(тип: str, глубина_м: float, K: float, *, труба_м: float, со_спо: bool, опз_без_пакера: bool, кратность_89: float) -> float:
    р = nv.РАЗОВЫЕ_Ч
    спо = nv.спо_цикл_мин(труб(глубина_м, труба_м), НКТ_ММ, АГРЕГАТ, АВТОМАТ) / 60.0 if со_спо else 0.0
    агрегат = р['§138 монтаж передвижного агрегата А-50, А-50У'] + р['§139 демонтаж передвижного агрегата А-50, А-50У']
    if тип == 'ГРП':
        постоянная = р['§77а расстановка технологического оборудования'] + р['§84б монтаж емкостей для нефти (4 x 14 м3)'] + р['§77б обвязка технологического оборудования'] + р['§77в опрессовка поверхностных коммуникаций'] + р['§86 проверка герметичности пакера опрессовкой'] + р['§87 определение приемистости пласта при гидроразрыве'] + р['§88 предварительная закачка нефти на режиме приемистости'] + р['§89 приготовление и закачка пульпы, на разовую операцию'] * кратность_89
        табличная = nv.табл(nv.НОРМЫ_90_СНЯТИЕ_ПАКЕРА_Ч, глубина_м)
    elif тип == 'ОПЗ':
        подг = р['§91а подготовительные работы без установки пакера'] if опз_без_пакера else р['§91б подготовительные работы с установкой пакера']
        постоянная = подг + р['§92 определение приемистости пласта'] + р['§93 перекачка кислоты из автоцистерны в мерные емкости'] + р['§94а приготовление раствора соляной кислоты'] + р['§96 ожидание действия кислоты на пласт'] + р['§97 подготовительные работы перед вымыванием и снятие пакера'] + р['§100 заключительные работы после вымывания и промывки']
        табличная = nv.табл(nv.НОРМЫ_95_ЗАКАЧКА_КИСЛОТЫ_Ч, глубина_м) + nv.табл(nv.НОРМЫ_98_ВЫМЫВАНИЕ_Ч, глубина_м)
    else:
        raise ValueError(f'тип {тип} нормативом не покрыт (ведомость 3.359)')
    return постоянная + агрегат + K * табличная + спо

def собрать(вариант: str='первичный') -> pl.DataFrame:
    труба_м = ТРУБА_М_ЧУВСТВ if вариант == 'труба 8 м' else ТРУБА_М
    со_спо = вариант != 'без СПО'
    без_пакера = вариант == 'ОПЗ §91а'
    полная = вариант == 'ГРП Н-полная'
    ev = pl.read_parquet(cfg.data('interim/gtm_events.parquet')).filter(pl.col('выбираемая') & pl.col('тип').is_in(ТИПЫ)).select('op_id', 'well_raw', 'тип', 'beg', 'dur')
    cap = pl.read_parquet(cfg.data('interim/capex_physical.parquet')).select('op_id', 'capex', 'проппант_т')
    t = ev.join(cap, on='op_id', how='left').join(глубины(ev), on='op_id', how='left').join(диаметры(ev), on='op_id', how='left')
    t = t.with_columns(кратность_89=pl.when(полная & (pl.col('тип') == 'ГРП') & (pl.col('проппант_т') > 0)).then(pl.col('проппант_т') / 10.0).otherwise(1.0))
    строки = []
    вне_диапазона = 0
    for r in t.iter_rows(named=True):
        if r['глубина_м'] is None or r['dur'] is None or r['capex'] is None:
            continue
        try:
            ч = норматив_ч(r['тип'], r['глубина_м'], r['K'], труба_м=труба_м, со_спо=со_спо, опз_без_пакера=без_пакера, кратность_89=r['кратность_89'])
        except ValueError:
            вне_диапазона += 1
            continue
        строки.append({'op_id': r['op_id'], 'тип': r['тип'], 'норматив_сут': ч / Ч_В_СУТКАХ, 'capex': r['capex'], 'dur': r['dur'], 'глубина_м': r['глубина_м'], 'K': r['K']})
    d = pl.DataFrame(строки)
    выпало = t.height - d.height
    print(f'вариант «{вариант}»: в сравнение вошло {d.height} из {t.height} операций двух типов; выпало {выпало} (из них вне нормативного диапазона глубин {вне_диапазона})')
    if вариант == 'первичный':
        _ЗАМЕР.update(вошло=d.height, выпало=выпало, вне_диапазона=вне_диапазона, пул_двух_типов=t.height)
    return d

def ро(a: np.ndarray, b: np.ndarray) -> float:
    ra, rb = (rankdata(a), rankdata(b))
    return float(np.corrcoef(ra, rb)[0, 1])

def сравнить(d: pl.DataFrame, тип: str, rng: np.random.Generator) -> dict:
    s = d.filter(pl.col('тип') == тип)
    н = s['норматив_сут'].to_numpy()
    наш = s['capex'].to_numpy()
    л1 = s['dur'].to_numpy()
    ро_наш, ро_л1 = (ро(н, наш), ро(н, л1))
    n = len(н)
    дельты = np.empty(РЕПЛИКАЦИЙ)
    for i in range(РЕПЛИКАЦИЙ):
        j = rng.integers(0, n, n)
        дельты[i] = ро(н[j], наш[j]) - ро(н[j], л1[j])
    lo, hi = np.percentile(дельты, [2.5, 97.5])
    дельта = ро_наш - ро_л1
    различимо = (lo > 0 or hi < 0) and abs(дельта) >= ПОРОГ_ДЕЛЬТА
    ниже = float((s['норматив_сут'] <= s['dur']).mean())
    return {'тип': тип, 'n': n, 'ро_наш': ро_наш, 'ро_л1': ро_л1, 'дельта': дельта, 'lo': float(lo), 'hi': float(hi), 'различимо': различимо, 'доля_ниже_факта': ниже, 'мед_норматив': float(s['норматив_сут'].median()), 'мед_факт': float(s['dur'].median())}

def исход(рез: dict[str, dict]) -> tuple[int, str]:
    р = [рез[т] for т in ТИПЫ]
    разл = [x['различимо'] for x in р]
    if all(разл) and all((x['дельта'] > 0 for x in р)):
        return (1, 'А1: наша модель затрат УПОРЯДОЧИВАЕТ операции ближе к внешней норме, чем конвенция, и это различимо на обоих типах')
    if all(разл) and all((x['дельта'] < 0 for x in р)):
        return (2, 'А2: КОНВЕНЦИЯ упорядочивает операции ближе к внешней норме, и это различимо на обоих типах. Исход объявлен допустимым до прогона (3.354) и идёт в статью как есть')
    if any(разл):
        return (3, 'А3: выводы по ОПЗ и ГРП РАСХОДЯТСЯ -- различимо не на обоих типах или с разными знаками. Типы печатаются порознь, усреднения нет')
    return (4, 'А4: разность НЕ РАЗЛИЧИМА ни на одном типе. Внешний арбитр двух моделей затрат не различает; вывод §8.5 о неразрешимости остаётся в силе, но теперь опирается на ИЗМЕРЕННУЮ неразличимость при НАЙДЕННОМ арбитре')

