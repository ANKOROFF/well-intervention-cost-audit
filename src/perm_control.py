"""Permutation control by year labels."""
import io
import itertools
import sys
from contextlib import redirect_stdout
import numpy as np
import polars as pl
import stats
from stats import LINES, dm_test, bootstrap_gc
B = 1000000000.0
ФАКТ = 'факт инженеров'
ОРАКУЛ = 'оракул по факту'
ВЫРОЖДЕННЫЙ = 'случайный отбор'
АЛЬФА = 0.05
СРАВНЕНИЙ_БОНФ = 3
ПОРОГ_БОНФ = АЛЬФА / СРАВНЕНИЙ_БОНФ
ЗАПАС_5_4 = 0.0179 - ПОРОГ_БОНФ

def t2(d):
    n = len(d)
    s = d.std(ddof=1)
    if not np.isfinite(s) or s <= 0:
        return np.nan
    return float(d.mean() / (s / np.sqrt(n)))

def перестановочное_p(d, знаки):
    T_набл = t2(d)
    if not np.isfinite(T_набл):
        return (np.nan, np.nan, 0, len(знаки), 0)
    absT = np.abs(np.array([t2(d * s) for s in знаки]))
    k = int((absT >= abs(T_набл) * (1 - 1e-12)).sum())
    уровней = len(np.unique(np.round(absT, 12)))
    return (T_набл, k / len(знаки), k, len(знаки), уровней)

def вердикт(p, порог):
    if p != p:
        return 'не определён'
    return 'значим' if p < порог else 'не значим'

def main():
    знаки = np.array(list(itertools.product([1, -1], repeat=9)))
    print('=' * 78)
    print('Э6. НЕВЫРОЖДЕННЫЙ ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ: ПЕРЕСТАНОВОЧНЫЙ ТЕСТ')
    print('=' * 78)
    print('\nОБЪЯВЛЕНО ДО ПРОГОНА (не после):')
    print(f'  статистика T объявлена как Т2 = d_ср / (s_d / sqrt(n)), форма ДМ;')
    print(f'  Т1 (сумма разностей) и Т3 (GC) пересчитываются в тех же перестановках')
    print(f'  и печатаются рядом, но вердикт выносится ТОЛЬКО по Т2: выбор лучшего')
    print(f'  из трёх p был бы скрытой множественностью сверх трёх сравнений.')
    print(f'  квант двустороннего p          = 2/512 = {2 / 512:.6f}')
    print(f'  минимально достижимое p        = {2 / 512:.6f} (не 1/512 = {1 / 512:.6f}),')
    print(f'    потому что T(-x) = -T(x) и каждое |T| встречается ровно дважды')
    print(f'  порог Бонферрони при {СРАВНЕНИЙ_БОНФ} сравн.  = {АЛЬФА}/{СРАВНЕНИЙ_БОНФ} = {ПОРОГ_БОНФ:.6f}')
    print(f'  запас строки 5.4 (p = 0.0179) до порога = {ЗАПАС_5_4:.6f} = {ЗАПАС_5_4 / (2 / 512):.2f} кванта')
    print(f'  СЛЕДСТВИЕ: вердикт о превосходстве над тривиальным правилом лежит')
    print(f'  ВНУТРИ одного кванта 2/512. Перестановочный тест не может его ни')
    print(f'  подтвердить, ни опровергнуть -- ни при каком исходе прогона ниже.')
    print(f"\n{'-' * 78}\nСЧЁТЧИКИ ОТБОРА\n{'-' * 78}")
    буфер = io.StringIO()
    with redirect_stdout(буфер):
        d, руб_т = stats.build()
        df, res = stats.report(d, руб_т, 1, 'Э6 источник парных разностей')
    print(f'  операций в таблице после сборки:            {d.height:>6,}')
    print(f'  цена тонны из фактического NPV:             {руб_т:>10,.0f} ₽/т')
    print(f'  лет в хронологическом прогоне:              {df.height:>6d}')
    print(f"  кандидатов в пуле, минимум по годам:        {df['кандидатов'].min():>6,}")
    print(f"  кандидатов в пуле, максимум по годам:       {df['кандидатов'].max():>6,}")
    print(f'  линий отчёта (включая факт и оракул):       {len(LINES):>6d}')
    print(f'  сравниваемых с фактом линий:                {len(LINES) - 1:>6d}')
    print(f'  знаковых расстановок в переборе:            {len(знаки):>6d} = 2^{df.height}')
    if df.height != 9:
        print(f'  ОСТАНОВ: лет {df.height}, а перебор построен на 9.')
        return 1
    v = {k: df[f'{k}|NPV'].to_numpy() / B for k in LINES}
    f, o = (v[ФАКТ], v[ОРАКУЛ])
    знаменатель_gc = float((o - f).sum())
    print(f'\n  ГОДОВЫЕ ПАРНЫЕ РАЗНОСТИ d_i = NPV(линия) - NPV(факт), млрд ₽:')
    таб = df.select('год')
    for k in LINES[1:]:
        таб = таб.with_columns(pl.Series(v[k] - f).round(4).alias(k))
    print(таб.to_pandas().to_string(index=False))
    print(f"\n{'-' * 78}\nТ2 -- ОСНОВНАЯ СТАТИСТИКА. ПЕРЕСТАНОВОЧНОЕ p ПРОТИВ ДМ\n{'-' * 78}")
    print(f"{'линия':26s} {'T набл.':>8s} {'перест. p':>11s} {'числ./512':>10s} {'ДМ p':>8s} {'вердикт перест.':>16s} {'вердикт ДМ':>12s} {'совпал':>7s}")
    строки = []
    for k in LINES[1:]:
        d_i = v[k] - f
        T, p_perm, числ, всего, уровней = перестановочное_p(d_i, знаки)
        dm, p_dm, n = dm_test(d_i)
        в_perm, в_dm = (вердикт(p_perm, АЛЬФА), вердикт(p_dm, АЛЬФА))
        совпал = 'да' if в_perm == в_dm else 'НЕТ'
        print(f'{k:26s} {T:8.3f} {p_perm:11.6f} {числ:6d}/{всего:<3d} {p_dm:8.4f} {в_perm:>16s} {в_dm:>12s} {совпал:>7s}')
        строки.append({'линия': k, 'T': T, 'p_perm': p_perm, 'числитель': числ, 'всего': всего, 'уровней_absT': уровней, 'ДМ': dm, 'p_ДМ': p_dm, 'лет': n, 'вердикт_perm': в_perm, 'вердикт_ДМ': в_dm, 'совпал': совпал})
    print(f"\n  Числитель ЧЁТНЫЙ у всех линий: {all((r['числитель'] % 2 == 0 for r in строки))}  -- воспроизводит src/perm_quantum.py")
    print(f"  Различных уровней |T| среди {len(знаки)} расстановок по линиям: {[r['уровней_absT'] for r in строки]}")
    print(f'  Ожидается ровно {len(знаки) // 2} = {len(знаки)}/2, потому что каждое |T|')
    print(f"  встречается дважды: {all((r['уровней_absT'] == len(знаки) // 2 for r in строки))}")
    print(f'  Достижимый минимум p на каждой линии: 2/{len(знаки)} = {2 / len(знаки):.6f}')
    смен = [r for r in строки if r['совпал'] == 'НЕТ']
    print(f'\n  ВЕРДИКТЫ ЗНАЧИМОСТИ при альфа = {АЛЬФА}: сменилось {len(смен)} из {len(строки)}')
    if смен:
        for r in смен:
            print(f"    {r['линия']}: ДМ p = {r['p_ДМ']:.4f} ({r['вердикт_ДМ']}) -> перест. p = {r['p_perm']:.6f} ({r['вердикт_perm']})")
    else:
        print(f'    ни один вердикт не сменился. Это РЕЗУЛЬТАТ, а не его отсутствие:')
        print(f'    головные числа работы не держались на непроверяемых предпосылках')
        print(f'    параметрического теста.')
    print(f'\n  ТО ЖЕ при пороге Бонферрони {ПОРОГ_БОНФ:.6f}:')
    for r in строки:
        вб_p, вб_dm = (вердикт(r['p_perm'], ПОРОГ_БОНФ), вердикт(r['p_ДМ'], ПОРОГ_БОНФ))
        print(f"    {r['линия']:26s} перест. {вб_p:>10s} | ДМ {вб_dm:>10s} | {('совпал' if вб_p == вб_dm else 'СМЕНИЛСЯ')}")
    print(f"\n{'-' * 78}\nТ1 И Т3 -- СОПРОВОЖДАЮЩИЕ. ВЕРДИКТ ПО НИМ НЕ ВЫНОСИТСЯ\n{'-' * 78}")
    print(f'  Т3 = GC = (линия - факт) / (оракул - факт). Знаменатель называется')
    print(f'  всегда: оракул - факт = {знаменатель_gc:.4f} млрд ₽ за {df.height} лет.')
    print(f'  Под сменой знаков числитель меняет знак, знаменатель НЕТ, поэтому')
    print(f'  перестановочное распределение Т3 -- это распределение Т1, делённое')
    print(f'  на постоянную, и p у Т1 и Т3 совпадают ТОЖДЕСТВЕННО. Печатаются оба,')
    print(f'  чтобы совпадение было видно, а не предполагалось.')
    print(f"\n{'линия':26s} {'Т1, млрд':>10s} {'p(Т1)':>10s} {'Т3 = GC':>9s} {'p(Т3)':>10s} {'p(Т2)':>10s}")
    for k in LINES[1:]:
        d_i = v[k] - f
        сумм = np.array([float((d_i * s).sum()) for s in знаки])
        p_t1 = float((np.abs(сумм) >= abs(d_i.sum()) * (1 - 1e-12)).sum()) / len(знаки)
        gc_набл = float(d_i.sum()) / знаменатель_gc
        gc_всех = сумм / знаменатель_gc
        p_t3 = float((np.abs(gc_всех) >= abs(gc_набл) * (1 - 1e-12)).sum()) / len(знаки)
        p_t2 = next((r['p_perm'] for r in строки if r['линия'] == k))
        print(f'{k:26s} {d_i.sum():10.4f} {p_t1:10.6f} {gc_набл:9.3f} {p_t3:10.6f} {p_t2:10.6f}')
    print(f"\n{'-' * 78}\nПРЕЖНИЙ ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ: СОХРАНЁН, ОБЪЯВЛЕН ВЫРОЖДЕННЫМ\n{'-' * 78}")
    r_выр = next((r for r in строки if r['линия'] == ВЫРОЖДЕННЫЙ))
    d_выр = v[ВЫРОЖДЕННЫЙ] - f
    gc, lo, hi, повторов = bootstrap_gc(v[ВЫРОЖДЕННЫЙ], f, o)
    print(f'  линия «{ВЫРОЖДЕННЫЙ}» НЕ УДАЛЕНА и считается наравне с прочими.')
    print(f'  NPV за {df.height} лет: {v[ВЫРОЖДЕННЫЙ].sum():.4f} млрд ₽ против факта {f.sum():.4f} млрд ₽')
    print(f'  разность: {d_выр.sum():+.4f} млрд ₽ = {100 * d_выр.sum() / f.sum():+.4f}% ОТ ФАКТА {f.sum():.4f} млрд ₽')
    print(f'    знаменатель доли назван ЯВНО: прежняя публикация давала 0.05% без')
    print(f'    названного знаменателя, и от факта портфеля доля иная.')
    print(f'  GC = {gc:.3f}, 95% ДИ [{lo:.3f}, {hi:.3f}], повторов бутстрэпа {повторов}')
    print(f"  ДМ p = {r_выр['p_ДМ']:.4f} | перестановочное p = {r_выр['p_perm']:.6f} = {r_выр['числитель']}/{r_выр['всего']}")
    print(f'\n  ПОЧЕМУ ВЫРОЖДЕН -- механизм, а не оценка:')
    print(f'    бюджет и ёмкость случайного отбора заданы РАВНЫМИ фактическим')
    print(f'    тратам года (stats.year_run: budget, cap = capex[fact].sum(),')
    print(f'    dur[fact].sum()). При полном бюджете отбор обязан взять ту же')
    print(f'    совокупность, что инженеры: бюджет в точности её и покрывает.')
    print(f'    Отбор пришпилен к факту ПО ПОСТРОЕНИЮ.')
    print(f'  ПРОВЕРЯЕМОЕ СЛЕДСТВИЕ -- годовые разности прижаты к нулю:')
    print(f'    максимум |d_i| у вырожденного контроля: {np.abs(d_выр).max():.4f} млрд ₽')
    for k in LINES[1:]:
        if k != ВЫРОЖДЕННЫЙ:
            print(f'    для сравнения, у «{k}»: {np.abs(v[k] - f).max():.4f} млрд ₽')
    print(f'  ВЕРДИКТ ЭТОГО КОНТРОЛЯ ПЕРЕВОРАЧИВАЛСЯ ДВАЖДЫ без изменения предмета:')
    print(f'    p = 0.5849 -> 0.0222 (Ш9) -> 0.0648 (Ш11). Это свидетельство')
    print(f'    вырожденности конструкции, а не измерение чего-либо.')
    print(f'  НИ ОДИН вердикт работы на числах этой линии не опирается. Действующий')
    print(f'  отрицательный контроль -- перестановочный тест выше.')
    print(f"\n{'-' * 78}\nЧТО ТЕСТ НЕ СДЕЛАЛ\n{'-' * 78}")
    print(f'  Мощности не добавилось: девять лет дают ровно девять бит, потолок')
    print(f'  разрешения -- квант 2/512 = {2 / 512:.6f}, и он не сдвигается ничем.')
    print(f'  Исправлена КАЛИБРОВКА p, а не мощность. Мощность -- предмет Э7.')
    print(f'  Утверждение о превосходстве над тривиальным правилом (запас {ЗАПАС_5_4:.6f}')
    print(f'  = {ЗАПАС_5_4 / (2 / 512):.2f} кванта) осталось неразрешимым, как и было объявлено до прогона.')
    return 0
if __name__ == '__main__':
    sys.exit(main())
