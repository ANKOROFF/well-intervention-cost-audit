"""Library: grid of budget multipliers, years and sensitivity-anchor names."""
ALPHAS = (1.0, 0.95, 0.9, 0.75, 0.5)
ГОДЫ = tuple(range(2016, 2025))
ЧУВСТВИТЕЛЬНОСТИ = ('только бюджет', 'усечение худшим вперёд')
ПОРОГ_P = 0.05
ПОРОГ_РЕАЛИЗМА_АЛЬФА = 0.75
R_УСЕЧЕНИЙ = 100
ПРИБОР = {'GC': 0.2631, 'GC_lo': 0.1772, 'GC_hi': 0.3453, 'ДМ': 4.29, 'p': 0.0027}

def a(alpha):
    return f'{alpha:.2f}'

def имена():
    yield 'проверка прибора пройдена 1 да 0 нет'
    yield 'наблюдённый минимум отношения бюджетов'
    for г in ГОДЫ:
        yield f'год {г} альфа звезда бюджет'
        yield f'год {г} альфа звезда ёмкость'
    yield 'альфа звезда бюджет минимум'
    yield 'альфа звезда бюджет медиана'
    yield 'альфа звезда бюджет максимум'
    yield 'альфа звезда ёмкость минимум'
    yield 'альфа звезда ёмкость медиана'
    yield 'альфа звезда ёмкость максимум'
    for alpha in ALPHAS:
        м = a(alpha)
        yield f'альфа {м} GC'
        yield f'альфа {м} GC ДИ низ'
        yield f'альфа {м} GC ДИ верх'
        yield f'альфа {м} повторов'
        yield f'альфа {м} ДМ'
        yield f'альфа {м} p'
        yield f'альфа {м} знаменатель млрд'
        yield f'альфа {м} GC розыгрыш минимум'
        yield f'альфа {м} GC розыгрыш медиана'
        yield f'альфа {м} GC розыгрыш максимум'
        yield f'альфа {м} лет со связыванием бюджета'
        yield f'альфа {м} лет со связыванием ёмкости'
        yield f'альфа {м} доля бюджета медиана'
        yield f'альфа {м} доля ёмкости медиана'
        yield f'альфа {м} усечено операций среднее'
        yield f'альфа {м} факт допустим 1 да 0 нет'
        yield f'альфа {м} условий из трёх выполнено'
        for г in ГОДЫ:
            yield f'альфа {м} год {г} доля бюджета'
            yield f'альфа {м} год {г} доля ёмкости'
            yield f'альфа {м} год {г} бюджет связывает 1 да 0 нет'
            yield f'альфа {м} год {г} ёмкость связывает 1 да 0 нет'
    yield 'наименьшая альфа со связыванием'
    yield 'наибольшая альфа со связыванием'
    yield 'флаг С1 1 да 0 нет'
    yield 'флаг С2 1 да 0 нет'
    yield 'флаг С3 1 да 0 нет'
    yield 'флаг С4 1 да 0 нет'
    yield 'номер вердикта'
    for ч in ЧУВСТВИТЕЛЬНОСТИ:
        for alpha in ALPHAS:
            м = a(alpha)
            yield f'чувствительность {ч} альфа {м} GC'
            yield f'чувствительность {ч} альфа {м} p'
            yield f'чувствительность {ч} альфа {м} условий из трёх выполнено'
        yield f'чувствительность {ч} номер вердикта'
        yield f'чувствительность {ч} вердикт не сменился 1 да 0 нет'
    yield 'все чувствительности вердикт не сменили 1 да 0 нет'
if __name__ == '__main__':
    сп = list(имена())
    print(f'якорей Э25: {len(сп)}, различных {len(set(сп))}')
    assert len(сп) == len(set(сп)), 'имена якорей обязаны быть различны'
