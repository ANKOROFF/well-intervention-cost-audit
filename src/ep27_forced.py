def закреплённый(метка: str, отборы, тип: dict[int, str], цены: dict[int, float] | None=None, отборы_оракула=None) -> dict:
    оа = отборы_оракула if отборы_оракула is not None else отборы
    f, v_св, o_св, v_зк, o_зк = ([], [], [], [], [])
    зкр_оп = св_оп = 0
    for г, го in zip(отборы, оа):
        ids = г['op_id'].tolist()
        assert ids == го['op_id'].tolist(), 'пулы клеток не совпадают по составу'
        знач = np.array([цены[i] for i in ids]) if цены is not None else г['npv']
        выну = np.array([тип.get(i) in ВЫНУЖД for i in ids])
        s_m, s_o = (г['отбор'][LINE], го['отбор'][ORACLE])
        m_зк = s_m & ~выну | выну
        o_зк_ = s_o & ~выну | выну
        f.append(float(знач.sum()))
        v_св.append(float(знач[s_m].sum()))
        o_св.append(float(знач[s_o].sum()))
        v_зк.append(float(знач[m_зк].sum()))
        o_зк.append(float(знач[o_зк_].sum()))
        св_оп += int(s_m.sum())
        зкр_оп += int(m_зк.sum())
    f, v_св, o_св = (np.array(f), np.array(v_св), np.array(o_св))
    v_зк, o_зк = (np.array(v_зк), np.array(o_зк))
    из_ = {}
    for имя, v, o in (('свободный отбор', v_св, o_св), ('ВЫНУЖДЕННЫЕ ЗАКРЕПЛЕНЫ', v_зк, o_зк)):
        stats.rng = np.random.default_rng(SEED)
        gc, lo, hi, reps = stats.bootstrap_gc(v, f, o)
        дм, p, лет = stats.dm_test((v - f) / B)
        из_[имя] = {'GC': gc, 'lo': lo, 'hi': hi, 'повторов': reps, 'ДМ': дм, 'p': p, 'лет': лет, 'NPV_факт': float(f.sum()) / B, 'NPV_модель': float(v.sum()) / B, 'NPV_оракул': float(o.sum()) / B, 'знаменатель': float((o - f).sum()) / B, 'числитель': float((v - f).sum()) / B}
    print(f"\n{'=' * 78}\nGC ПРИ ЗАКРЕПЛЁННЫХ ВЫНУЖДЕННЫХ ТИПАХ, клетка «{метка}» (ведомость 3.411)\n{'=' * 78}")
    print(f"  {'постановка':24s} {'GC':>8s} {'95% ДИ':>19s} {'повт.':>6s} {'ДМ':>7s} {'p':>8s} {'числ.':>8s} {'знам.':>8s} {'NPV факт':>9s} {'NPV мод.':>9s} {'NPV орк.':>9s}")
    for имя, r in из_.items():
        print(f"  {имя:24s} {r['GC']:8.4f} [{r['lo']:8.4f}, {r['hi']:7.4f}] {r['повторов']:6d} {r['ДМ']:7.2f} {r['p']:8.4f} {r['числитель']:8.4f} {r['знаменатель']:8.4f} {r['NPV_факт']:9.4f} {r['NPV_модель']:9.4f} {r['NPV_оракул']:9.4f}")
    а, б = (из_['свободный отбор'], из_['ВЫНУЖДЕННЫЕ ЗАКРЕПЛЕНЫ'])
    из_['сокращение числителя'] = а['числитель'] - б['числитель']
    из_['сокращение знаменателя'] = а['знаменатель'] - б['знаменатель']
    print(f"  сокращение числителя {из_['сокращение числителя']:.4f} млрд ₽ против сокращения знаменателя {из_['сокращение знаменателя']:.4f} млрд ₽ -- во столько раз ({из_['сокращение знаменателя'] / абс(из_['сокращение числителя']):.4f}) вынужденные работы связывают оракула сильнее, чем нашу модель")
    print(f"  изменение GC: {б['GC'] - а['GC']:+.4f} ({100 * (б['GC'] - а['GC']) / абс(а['GC']):+.1f}% от свободного)")
    print(f"  ДИ пересекаются: {('ДА' if min(а['hi'], б['hi']) >= max(а['lo'], б['lo']) else 'НЕТ')}; точечная оценка закреплённой постановки лежит {('ВНУТРИ' if а['lo'] <= б['GC'] <= а['hi'] else 'ВНЕ')} интервала свободной")
    print(f'  операций отобрано за девять лет: свободно {св_оп}, при закреплении {зкр_оп} (прирост {зкр_оп - св_оп})')
    return из_

