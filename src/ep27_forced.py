        s_m = г['отбор'][LINE]
        отк = ~s_m
        прирост = float(-знач[отк].sum())
        вкл_в = float(-знач[отк & выну].sum())
        вкл_д = float(-знач[отк & ~выну].sum())
        масштаб = max(abs(float(знач.sum())), abs(прирост), 1.0)
        годна = abs(прирост) > 1e-09 * масштаб
        по_годам[int(г['год'])] = {'прирост': прирост, 'вынужд': вкл_в, 'дискр': вкл_д, 'доля': вкл_в / прирост if годна else float('nan'), 'годна': годна, 'оп_пула': len(ids), 'отказано': int(отк.sum()), 'отказано_в': int((отк & выну).sum()), 'вынужд_в_пуле': int(выну.sum())}
