def дор(метка: str, отборы, тип: dict[int, str], цены: dict[int, float] | None=None, отборы_оракула=None) -> dict:
    оа = отборы_оракула if отборы_оракула is not None else отборы
    f, v_св, v_зк, o_св, годы = ([], [], [], [], [])
    for г, го in zip(отборы, оа):
        годы.append(int(г['год']))
        ids = г['op_id'].tolist()
        знач = np.array([цены[i] for i in ids]) if цены is not None else г['npv']
        выну = np.array([тип.get(i) in ВЫНУЖД for i in ids])
        s_m = г['отбор'][LINE]
        f.append(float(знач.sum()))
        v_св.append(float(знач[s_m].sum()))
        v_зк.append(float(знач[s_m & ~выну | выну].sum()))
        o_св.append(float(знач[го['отбор'][ORACLE]].sum()))
    f = np.array(f)
    v_св, v_зк, o_св = (np.array(v_св), np.array(v_зк), np.array(o_св))
    д_своя = float((o_св - f).sum()) / B
    из_ = {'D_своя': д_своя, 'D_общая': Д_ОБЩ}
    for имя_D, D in (('своя клетка', д_своя), ('общая D', Д_ОБЩ)):
        for имя_п, v in (('свободная', v_св), ('закреплённая', v_зк)):
            чис = float((v - f).sum()) / B
            stats.rng = np.random.default_rng(SEED)
            повт = [float((v[i] - f[i]).sum()) / B / D for i in (stats.rng.integers(0, len(f), len(f)) for _ in range(2000))]
            г_ = np.array(повт)
            из_[имя_D, имя_п] = {'ДОР': чис / D, 'числитель': чис, 'D': D, 'lo': float(np.percentile(г_, 2.5)), 'hi': float(np.percentile(г_, 97.5)), 'повторов': len(г_)}
        раз = (v_зк - v_св) / B
        stats.rng = np.random.default_rng(SEED)
        сум = np.array([раз[stats.rng.integers(0, len(раз), len(раз))].sum() / D for _ in range(2000)])
        дм, pv, лет = stats.dm_test(раз)
        из_[имя_D, 'вход'] = {'лет': len(раз), 'вектор': [float(x) for x in раз], 'отрицательных лет': int((раз < 0).sum()), 'положительных лет': int((раз > 0).sum()), 'нулевых лет': int((раз == 0).sum()), 'среднее': float(раз.mean()), 'сумма': float(раз.sum()), 'сумма_на_D': float(раз.sum()) / D, 'девять_средних_на_D': float(9 * раз.mean()) / D, 'ст_откл': float(раз.std(ddof=0)), 'макс_по_модулю': float(np.abs(раз).max()), 'доля_макс_в_сумме': float(np.abs(раз).max() / abs(раз.sum())) if раз.sum() else float('nan'), 'годы': годы, 'по_годам': {г: float(x) for г, x in zip(годы, раз)}, 'сумма_2016_2017': float(sum((x for г, x in zip(годы, раз) if г in (2016, 2017)))), 'нулевых_лет_годы': [г for г, x in zip(годы, раз) if x == 0.0], 'положительных_лет_годы': [г for г, x in zip(годы, раз) if x > 0.0]}
        из_[имя_D, 'разность'] = {'разность': float(раз.sum()) / D, 'lo': float(np.percentile(сум, 2.5)), 'hi': float(np.percentile(сум, 97.5)), 'ДМ': дм, 'p': pv, 'лет': лет, 'повторов': len(сум)}
    print(f"\n{'=' * 78}\nДОР НА ЗАФИКСИРОВАННОМ ЗНАМЕНАТЕЛЕ, клетка «{метка}» (ведомость 3.465-3.471)\n{'=' * 78}")
    print(f'  знаменатель своей клетки {д_своя:.4f} млрд ₽; общий {Д_ОБЩ:.4f} млрд ₽')
    print(f"  {'знаменатель':16s} {'постановка':14s} {'числ., млрд':>12s} {'ДОР':>8s} {'95% ДИ':>19s} {'повт.':>6s}")
    for имя_D in ('своя клетка', 'общая D'):
        for имя_п in ('свободная', 'закреплённая'):
            r = из_[имя_D, имя_п]
            print(f"  {имя_D:16s} {имя_п:14s} {r['числитель']:12.4f} {r['ДОР']:8.4f} [{r['lo']:8.4f}, {r['hi']:7.4f}] {r['повторов']:6d}")
        d = из_[имя_D, 'разность']
        знак = 'ПАДАЕТ' if d['разность'] < 0 else 'РАСТЁТ' if d['разность'] > 0 else 'не меняется'
        разл = 'ДИ ноль НЕ накрывает' if d['lo'] > 0 or d['hi'] < 0 else 'ДИ НАКРЫВАЕТ ноль'
        print(f"  {имя_D:16s} разность «закреплённая − свободная» {d['разность']:+.4f} [{d['lo']:+.4f}, {d['hi']:+.4f}] -> {знак}, {разл}; ДМ {d['ДМ']:.2f}, p = {d['p']:.4f}, лет {d['лет']}")
    в = из_['общая D', 'вход']
    print(f'\n  ЧТО КАЖДЫЙ ПРИБОР БЕРЁТ НА ВХОД (проверено прогоном, не описано):')
