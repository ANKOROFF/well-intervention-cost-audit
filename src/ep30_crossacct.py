"""Cross-accounting 2x2 matrix: selecting representation x valuing representation."""
from __future__ import annotations
import config as cfg
import pathlib
import sys
import numpy as np
import polars as pl
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import ep19_crossruler as e19
import stats
from ep06_ablation import _ди_суммы, _ряд_линейкой, _цены
from sdt_analysis import цепь
B = 1000000000.0
TOL = 0.0001
LINE = e19.LINE
TSV = cfg.out('ep30_crossacct.tsv')
TSV_ГОДЫ = cfg.out('ep30_crossacct_years.tsv')
ОЖИД = {'GC_НН': 0.2631, 'lo_НН': 0.1772, 'hi_НН': 0.3453, 'знам_Н': float('nan'), 'V_НЛ1': 0.2123, 'lo_НЛ1': 0.1045, 'hi_НЛ1': 0.3009, 'V_Л1Л1': 0.3479, 'NPV_НЛ1': float('nan'), 'факт_Л1': float('nan'), 'знам_Л1': float('nan')}

def якорь(имя: str, знач, ф: str='.4f') -> None:
    print(f'ЯКОРЬ {имя} = {format(знач, ф)}')

def сверить(имя: str, got: float, want: float) -> bool:
    ok = abs(got - want) <= TOL
    print(f"  РЕГРЕССИЯ {имя}: {got:.4f} против {want:.4f} -> {('сошлось' if ok else 'РАСХОЖДЕНИЕ')}")
    return ok

def собрать():
    cap = pl.read_parquet(e19.CAP_ПП)
    наш, л1 = цепь('ep30', cap)
    if наш['n'] != e19.N_ОБЪЯВЛЕНО or л1['n'] != e19.N_ОБЪЯВЛЕНО:
        print(f"ОСТАНОВ: n = {наш['n']} / {л1['n']} против {e19.N_ОБЪЯВЛЕНО}")
        sys.exit(1)
    return (наш, л1)

def главная() -> int:
    print('=== Б1.1: МАТРИЦА ПЕРЕКРЁСТНОГО УЧЁТА 2x2, цепь ППП (5 806 операций, 9 лет) ===')
    print('правило чтения: docs/epic/b1_reading_rules.md, раздел 1 (записано до расчёта)')
    рез = {'Н': None, 'Л1': None}
    рез['Н'], рез['Л1'] = собрать()
    n_ = рез['Н']['n']
    print(f"совокупность: {n_} операций у обеих цепей; лет {рез['Н']['лет']}")
    g = рез['Н']['линии'][LINE]
    ok = all([сверить('GC(ППП)', g['GC'], ОЖИД['GC_НН']), сверить('GC(ППП) ДИ низ', g['lo'], ОЖИД['lo_НН']), сверить('GC(ППП) ДИ верх', g['hi'], ОЖИД['hi_НН']), сверить('знаменатель Н', рез['Н']['разрыв'], ОЖИД['знам_Н']), сверить('знаменатель Л1', рез['Л1']['разрыв'], ОЖИД['знам_Л1'])])
    цены = {к: _цены(рез[к]) for к in рез}
    f = {к: рез[к]['df']['факт инженеров|NPV'].to_numpy() for к in рез}
    o = {к: рез[к]['df']['оракул по факту|NPV'].to_numpy() for к in рез}
    ряд = {(x, y): _ряд_линейкой(рез[x]['отборы'], цены[y], LINE) for x in рез for y in рез}
    яч = {}
    for (x, y), r in ряд.items():
        яч[x, y] = e19.доля(r, f[y], o[y])
    ok &= сверить('V_НН (доля)', яч['Н', 'Н']['доля'], ОЖИД['GC_НН'])
    ok &= сверить('V_НЛ1', яч['Н', 'Л1']['доля'], ОЖИД['V_НЛ1'])
    ok &= сверить('V_НЛ1 ДИ низ', яч['Н', 'Л1']['lo'], ОЖИД['lo_НЛ1'])
    ok &= сверить('V_НЛ1 ДИ верх', яч['Н', 'Л1']['hi'], ОЖИД['hi_НЛ1'])
    ok &= сверить('V_Л1Л1', яч['Л1', 'Л1']['доля'], ОЖИД['V_Л1Л1'])
    ok &= сверить('NPV отбора Н под Л1, млрд', яч['Н', 'Л1']['NPV'], ОЖИД['NPV_НЛ1'])
    ok &= сверить('факт инженеров под Л1, млрд', float(f['Л1'].sum()) / B, ОЖИД['факт_Л1'])
    if not ok:
        print('\nОСТАНОВ по п. 0.3 / 1.4 правил: регрессия не сошлась.')
        return 1
    знам = {y: рез[y]['разрыв'] for y in рез}
    print('\nЧЕТЫРЕ КЛЕТКИ. V_XY = отбор по X, оценка ценами Y; GC_XY = (V_XY - факт_Y)/(оракул_Y - факт_Y); знаменатель зависит только от Y, столбцы не складываются.')
    print(f"{'клетка':8s} {'NPV,млрд':>9s} {'dNPV,млрд':>10s} {'GC':>8s} {'95% ДИ (доля)':>20s} {'повт.':>6s} {'ДМ':>6s} {'p':>7s} {'знам.,млрд':>11s}")
    строки = []
    for (x, y), д in яч.items():
        dn = д['NPV'] - float(f[y].sum()) / B
        print(f"V_{x}{y:3s}  {д['NPV']:9.4f} {dn:10.4f} {д['доля']:8.4f} [{д['lo']:8.4f},{д['hi']:8.4f}] {д['повторов']:6d} {д['ДМ']:6.2f} {д['p']:7.4f} {знам[y]:11.4f}")
        строки.append((x, y, д, dn))
        имя = f'V_{x}{y}'
        якорь(f'{имя} NPV млрд', д['NPV'])
        якорь(f'{имя} dNPV млрд', dn)
        якорь(f'{имя} GC', д['доля'])
        якорь(f'{имя} GC ДИ низ', д['lo'])
        якорь(f'{имя} GC ДИ верх', д['hi'])
        якорь(f'{имя} повторов', д['повторов'], 'd')
        якорь(f'{имя} ДМ', д['ДМ'], '.2f')
        якорь(f'{имя} p', д['p'])
    for y in рез:
        якорь(f'знаменатель {y} млрд', знам[y])
        якорь(f'факт {y} млрд', float(f[y].sum()) / B)
        якорь(f'оракул {y} млрд', float(o[y].sum()) / B)
    print('\nГОДОВЫЕ РАЗНОСТИ d_Y,i = V_НY,i - V_Л1Y,i, млрд руб (знак +: отбор Н выше)')
    Δ = {}
    for y in рез:
        d = ряд['Н', y] - ряд['Л1', y]
        rng = np.random.default_rng(e19.SEED)
        lo, hi, reps = _ди_суммы(d, rng)
        dm, pv, _ = stats.dm_test(d / B)
        Δ[y] = {'сумма': float(d.sum()) / B, 'lo': lo / B, 'hi': hi / B, 'повт': reps, 'ДМ': dm, 'p': pv, 'd': d / B}
        print(f'  оценка {y:2s}: ' + ' '.join((f'{v:+.3f}' for v in d / B)))
        print(f"    Δ_{y} = {Δ[y]['сумма']:+.4f} [{Δ[y]['lo']:+.4f}, {Δ[y]['hi']:+.4f}], повторов {reps}, ДМ {dm:.2f}, p = {pv:.4f} (ДМ справочно)")
        якорь(f'Δ_{y} млрд', Δ[y]['сумма'])
        якорь(f'Δ_{y} ДИ низ', Δ[y]['lo'])
        якорь(f'Δ_{y} ДИ верх', Δ[y]['hi'])
        якорь(f'Δ_{y} повторов', reps, 'd')
        якорь(f'Δ_{y} ДМ', dm, '.2f')
        якорь(f'Δ_{y} p', pv)

    def различимо(q):
        return q['lo'] > 0 or q['hi'] < 0
    ΔН, ΔЛ = (Δ['Н'], Δ['Л1'])
    if различимо(ΔН) and различимо(ΔЛ) and (np.sign(ΔН['сумма']) == np.sign(ΔЛ['сумма'])):
        код, нзв = ('К-A+', 'отбор Н выше под обоими оценщиками') if ΔН['сумма'] > 0 else ('К-A-', 'отбор Л1 выше под обоими оценщиками')
    elif различимо(ΔН) and различимо(ΔЛ) and (np.sign(ΔН['сумма']) != np.sign(ΔЛ['сумма'])):
        if ΔН['сумма'] > 0:
            код, нзв = ('К-B1', 'каждая спецификация предпочитает собственный отбор')
        else:
            код, нзв = ('К-B2', 'каждая спецификация предпочитает чужой отбор')
    else:
        код, нзв = ('К-C', 'смешанный: различимого разворота или совпадения порядка нет')
    print('\n' + '=' * 78)
    print(f'ВЕРДИКТ ПО ПРАВИЛУ 1.6: НАСТУПИЛ ИСХОД {код} -- {нзв}')
    print('=' * 78)
    print(f"  Δ_Н {('различим' if различимо(ΔН) else 'ДИ накрывает ноль')}, Δ_Л1 {('различим' if различимо(ΔЛ) else 'ДИ накрывает ноль')}; знаки {np.sign(ΔН['сумма']):+.0f} / {np.sign(ΔЛ['сумма']):+.0f}")
    якорь('номер исхода (1 К-A+, 2 К-A-, 3 К-B1, 4 К-B2, 5 К-C)', {'К-A+': 1, 'К-A-': 2, 'К-B1': 3, 'К-B2': 4, 'К-C': 5}[код], 'd')
    print('\nДИАГНОСТИКА ДОПУСТИМОСТИ (отбор X по ценам Y, без пересчёта; п. 1.2):')
    cap_ = {y: {} for y in рез}
    dur_ = {y: {} for y in рез}
    for y in рез:
        for г in рез[y]['отборы']:
            cap_[y].update(zip(г['op_id'].tolist(), г['capex'].tolist()))
            dur_[y].update(zip(г['op_id'].tolist(), г['dur'].tolist()))
    for x in рез:
        for y in рез:
            нб = нс = 0
            for г in рез[x]['отборы']:
                ids = г['op_id'][г['отбор'][LINE]].tolist()
                гy = next((h for h in рез[y]['отборы'] if h['год'] == г['год']))
                нб += sum((cap_[y][i] for i in ids)) > гy['бюджет']
                нс += sum((dur_[y][i] for i in ids)) > гy['ёмкость']
            print(f'  отбор {x:2s} под ценами {y:2s}: лет с превышением бюджета {нб} из 9, ёмкости {нс} из 9')
            якорь(f'лет превышения бюджета отбор {x} цены {y}', нб, 'd')
            якорь(f'лет превышения ёмкости отбор {x} цены {y}', нс, 'd')

    def мн(r, k=LINE):
        return {(г['год'], i) for г in r['отборы'] for i in г['op_id'][г['отбор'][k]].tolist()}
    S = {x: мн(рез[x]) for x in рез}
    F = мн(рез['Н'], 'факт инженеров')
    I, U = (len(S['Н'] & S['Л1']), len(S['Н'] | S['Л1']))
    симм = S['Н'] ^ S['Л1']
    print(f'\nСОСТАВ ПРОГРАММ (линия «{LINE}», по парам год-операция):')
    print(f"  |S_Н| = {len(S['Н'])}, |S_Л1| = {len(S['Л1'])}, пересечение {I}, объединение {U}, Жаккар {I / U:.4f}, симметрическая разность {len(симм)}")
    якорь('Жаккар Н и Л1', I / U)
    якорь('симметрическая разность Н и Л1 операций', len(симм), 'd')
    якорь('размер S_Н', len(S['Н']), 'd')
    якорь('размер S_Л1', len(S['Л1']), 'd')
    for x in рез:
        доб, уд = (len(S[x] - F), len(F - S[x]))
        print(f'  {x:2s}: добавлений относительно факта {доб}, удалений {уд}, размер факта {len(F)}')
        якорь(f'добавления {x} к факту', доб, 'd')
        якорь(f'удаления {x} из факта', уд, 'd')
    якорь('размер факта инженеров', len(F), 'd')
    разн_знак = sum((1 for _, i in симм if (цены['Н'][i] > 0) != (цены['Л1'][i] > 0)))
    print(f'  операций симметрической разности с разным знаком NPV под Н и Л1: {разн_знак} из {len(симм)}')
    якорь('операций симм. разности с разным знаком NPV', разн_знак, 'd')
    print('\nСВОДКА ПО ГОДАМ (NPV отбора, млрд руб; факт и оракул под своей ценой):')
    print(f"{'год':>5s} {'V_НН':>8s} {'V_НЛ1':>8s} {'V_Л1Н':>8s} {'V_Л1Л1':>8s} {'факт_Н':>8s} {'факт_Л1':>8s} {'ор_Н':>8s} {'ор_Л1':>8s} {'|S_Н|':>6s} {'|S_Л1|':>6s} {'Жакк.':>6s}")
    годы = [г['год'] for г in рез['Н']['отборы']]
    tsv_g = ['год\tV_НН\tV_НЛ1\tV_Л1Н\tV_Л1Л1\tфакт_Н\tфакт_Л1\tоракул_Н\tоракул_Л1\tS_Н\tS_Л1\tЖаккар']
    for k, Y in enumerate(годы):
        a = {(x, y): ряд[x, y][k] / B for x in рез for y in рез}
        sн = {i for yy, i in S['Н'] if yy == Y}
        sл = {i for yy, i in S['Л1'] if yy == Y}
        ж = len(sн & sл) / len(sн | sл) if sн | sл else float('nan')
        vals = [a['Н', 'Н'], a['Н', 'Л1'], a['Л1', 'Н'], a['Л1', 'Л1'], f['Н'][k] / B, f['Л1'][k] / B, o['Н'][k] / B, o['Л1'][k] / B]
        print(f'{Y:5d} ' + ' '.join((f'{v:8.3f}' for v in vals)) + f' {len(sн):6d} {len(sл):6d} {ж:6.3f}')
        tsv_g.append('\t'.join([str(Y)] + [f'{v:.4f}' for v in vals] + [str(len(sн)), str(len(sл)), f'{ж:.4f}']))
    pathlib.Path(TSV_ГОДЫ).write_text('\n'.join(tsv_g) + '\n', encoding='utf-8')
    tsv = ['клетка\tотбор\tоценка\tNPV_млрд\tdNPV_млрд\tGC\tДИ_низ\tДИ_верх\tповторов\tДМ\tp\tзнаменатель_млрд']
    for x, y, д, dn in строки:
        tsv.append('\t'.join([f'V_{x}{y}', x, y, f"{д['NPV']:.4f}", f'{dn:.4f}', f"{д['доля']:.4f}", f"{д['lo']:.4f}", f"{д['hi']:.4f}", str(д['повторов']), f"{д['ДМ']:.2f}", f"{д['p']:.4f}", f'{знам[y]:.4f}']))
    for y in рез:
        tsv.append('\t'.join([f'Δ_{y}', 'Н минус Л1', y, f"{Δ[y]['сумма']:.4f}", '', '', f"{Δ[y]['lo']:.4f}", f"{Δ[y]['hi']:.4f}", str(Δ[y]['повт']), f"{Δ[y]['ДМ']:.2f}", f"{Δ[y]['p']:.4f}", '']))
    pathlib.Path(TSV).write_text('\n'.join(tsv) + '\n', encoding='utf-8')
    print(f'\nтаблицы: {TSV}, {TSV_ГОДЫ}')
    print('\nЧЕГО ЗАМЕР НЕ ДЕЛАЕТ: не утверждает, что одна спецификация затрат точнее другой; отбор не пересчитывается под чужие цены; ΔNPV, GC и Жаккар -- три разных вопроса. Внешнего арбитра в данных нет.')
    return 0
if __name__ == '__main__':
    sys.exit(главная())
