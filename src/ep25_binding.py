class Перехват:

    def __init__(self, alpha, только_бюджет=False):
        self.alpha = alpha
        self.только_бюджет = только_бюджет
        self.подлинная = stats.greedy
        self.вызовы = []

    def __call__(self, score, capex, dur, budget, cap, positive=True):
        b = budget * self.alpha
        c = cap if self.только_бюджет else cap * self.alpha
        sel = self.подлинная(score, capex, dur, b, c, positive=positive)
        if positive:
            self.вызовы.append({'score': np.asarray(score, float), 'capex': np.asarray(capex, float), 'dur': np.asarray(dur, float), 'budget': float(b), 'cap': float(c), 'sel': sel})
        return sel

def усечь(порядок, capex, dur, budget, cap):
    keep = np.zeros(len(capex), bool)
    b = c = 0.0
    for i in порядок:
        if b + capex[i] <= budget and c + dur[i] <= cap:
            keep[i] = True
            b += capex[i]
            c += dur[i]
    return keep

def прогон_года(d, руб_т, Y, alpha, только_бюджет, rng_ус):
    пер = Перехват(alpha, только_бюджет)
    stats.greedy = пер
    try:
        buf = io.StringIO()
        with contextlib.redirect_stdout(buf):
            out = stats.year_run(d, руб_т, Y, 1)
    finally:
        stats.greedy = пер.подлинная
    if out is None:
        return None
    assert len(пер.вызовы) == 4, f'{Y}: положительных вызовов greedy ожидалось 4, получено {len(пер.вызовы)} -- порядок линий в stats.year_run изменился'
    гол, орк = (пер.вызовы[2], пер.вызовы[3])
    capex, dur = (гол['capex'], гол['dur'])
    npv = орк['score'] * орк['dur']
    assert np.allclose(орк['dur'], dur), f'{Y}: пулы линий разошлись'
    бюджет, ёмкость = (гол['budget'], гол['cap'])
    полный_б, полная_ё = (capex.sum(), dur.sum())
    assert abs(бюджет / alpha - полный_б) <= ОТН_ДОПУСК * полный_б, f'{Y}: бюджет не равен alpha x сумме затрат пула -- pool_span не 1?'
    поз = гол['score'] > 0
    зв_б = float(capex[поз].sum() / полный_б) if полный_б > 0 else float('nan')
    зв_ё = float(dur[поз].sum() / полная_ё) if полная_ё > 0 else float('nan')
    свяж_б = bool(capex[поз].sum() > бюджет * (1 + ОТН_ДОПУСК))
    свяж_ё = bool(dur[поз].sum() > ёмкость * (1 + ОТН_ДОПУСК))

    def доля(в, рес, огр):
        return float(рес[в['sel']].sum() / огр) if огр > 0 else float('nan')
    факт_допустим = bool(полный_б <= бюджет * (1 + ОТН_ДОПУСК) and полная_ё <= ёмкость * (1 + ОТН_ДОПУСК))
    if факт_допустим:
        f_сл = np.full(g.R_УСЕЧЕНИЙ, float(npv.sum()))
        f_худ = float(npv.sum())
        усечено = 0.0
    else:
        keep = [усечь(rng_ус.permutation(len(npv)), capex, dur, бюджет, ёмкость) for _ in range(g.R_УСЕЧЕНИЙ)]
        f_сл = np.array([float(npv[k].sum()) for k in keep])
        усечено = float(np.mean([int((~k).sum()) for k in keep]))
        f_худ = float(npv[усечь(np.argsort(npv), capex, dur, бюджет, ёмкость)].sum())
    return {'год': Y, 'out': out, 'бюджет': бюджет, 'ёмкость': ёмкость, 'полный_б': float(полный_б), 'полная_ё': float(полная_ё), 'зв_б': зв_б, 'зв_ё': зв_ё, 'свяж_б': свяж_б, 'свяж_ё': свяж_ё, 'доля_б': доля(гол, capex, бюджет), 'доля_ё': доля(гол, dur, ёмкость), 'доля_б_орк': доля(орк, capex, бюджет), 'доля_ё_орк': доля(орк, dur, ёмкость), 'факт_допустим': факт_допустим, 'усечено': усечено, 'f_сл': f_сл, 'f_худ': f_худ, 'f_ср': float(f_сл.mean()), 'оп_поз': int(поз.sum()), 'оп_пул': int(len(npv)), 'оп_гол': int(гол['sel'].sum()), 'оп_орк': int(орк['sel'].sum())}

def пройти(d, руб_т, alpha, только_бюджет):
    stats.rng = np.random.default_rng(ce.SEED)
    rng_ус = np.random.default_rng(ce.SEED)
    rows = [r for Y in g.ГОДЫ if (r := прогон_года(d, руб_т, Y, alpha, только_бюджет, rng_ус))]
    assert rows, f'alpha {alpha}: ни один год не прошёл отбор year_run'
    return rows

def свести(rows, базис):
    v = {k: np.array([float(r['out'][f'{k}|NPV']) for r in rows]) for k in stats.LINES}
    f = np.array([r['f_ср'] if базис == 'ср' else r['f_худ'] for r in rows])
    o = v[ОРК]
    ди = {}
    for k in stats.LINES:
        ди[k] = stats.bootstrap_gc(v[k], f, o)
    gc, lo, hi, reps = ди[ГОЛ]
    dm, p, n = stats.dm_test((v[ГОЛ] - f) / B)
    знам = float((o - f).sum() / B)
    F = np.array([r['f_сл'] for r in rows])
    если = [(v[ГОЛ] - F[:, j]).sum() / (o - F[:, j]).sum() for j in range(F.shape[1]) if abs((o - F[:, j]).sum()) > 0]
    роз = (float(np.min(если)), float(np.median(если)), float(np.max(если)))
    условий = int(gc > 0) + int(p < g.ПОРОГ_P) + int(lo > 0)
    return {'GC': float(gc), 'lo': float(lo), 'hi': float(hi), 'reps': int(reps), 'ДМ': float(dm), 'p': float(p), 'знам': знам, 'роз': роз, 'условий': условий, 'лет': int(n), 'v': v, 'f': f, 'o': o}

def состояние(rng):
    return rng.bit_generator.state

def вернуть(rng, с):
    rng.bit_generator.state = с

def флаги(сетка, зв_б_медиана):
    связ = [a for a, (rows, s) in сетка.items() if any((r['свяж_б'] or r['свяж_ё'] for r in rows))]
    есть = bool(связ)
    с1 = есть and all((сетка[a][1]['условий'] == 3 for a in связ))
    с2 = есть and (not с1)
    if есть:
        rows_min = сетка[min(связ)][0]
        с3 = bool(sum((r['усечено'] for r in rows_min)) > 0)
    else:
        с3 = False
    с4 = bool(not есть or зв_б_медиана <= g.ПОРОГ_РЕАЛИЗМА_АЛЬФА)
    номер = 2 if с2 else 4 if с4 else 3 if с3 else 1
    return {'С1': с1, 'С2': с2, 'С3': с3, 'С4': с4, 'номер': номер, 'связ': связ}
