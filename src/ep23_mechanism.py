def признаки(база: pl.DataFrame, op_ids: list[int], ставка_л1: float, цены_наш: dict, цены_л1: dict) -> pl.DataFrame:
    t = база.filter(pl.col('op_id').is_in(op_ids))
    пред = pl.read_parquet(cfg.data('interim/dur_pred.parquet')).select('op_id', 'dur_пред')
    дм_типа = t.group_by('тип').agg(доля_матчасти_типа=pl.col('c_материалы_исп').sum() / pl.col('capex').sum())
    t = t.join(пред, on='op_id', how='left').join(дм_типа, on='тип', how='left')
    return t.select('op_id', 'тип', **{'ро CAPEX Л1 к нашему': pl.col('dur').fill_null(0.0) * ставка_л1 / pl.col('capex').clip(1.0, None), 'доля матчасти операции': pl.col('c_материалы_исп') / pl.col('capex').clip(1.0, None), 'доля матчасти типа': pl.col('доля_матчасти_типа'), 'длительность сырая сут': pl.col('dur'), 'длительность прогнозная сут': pl.col('dur_пред'), 'CAPEX наш млн': pl.col('capex') / 1000000.0, 'CAPEX Л1 млн': pl.col('dur').fill_null(0.0) * ставка_л1 / 1000000.0, 'мощность насоса кВт': pl.col('насос_мощность')}).join(pl.DataFrame({'op_id': list(цены_наш), 'NPV наш млн': [v / 1000000.0 for v in цены_наш.values()]}), on='op_id', how='left').join(pl.DataFrame({'op_id': list(цены_л1), 'NPV Л1 млн': [v / 1000000.0 for v in цены_л1.values()]}), on='op_id', how='left')

def группы(наш: dict, л1: dict, линия: str) -> dict:
    из_ = {'л1': [], 'наш': []}
    npv = {'л1': 0.0, 'наш': 0.0}
    for г1, г2 in zip(наш['отборы'], л1['отборы']):
        assert (г1['op_id'] == г2['op_id']).all(), 'пулы года разошлись'
        a, b = (г1['отбор'][линия], г2['отбор'][линия])
        для = {'наш': a & ~b, 'л1': b & ~a}
        for к, м in для.items():
            из_[к].extend(г1['op_id'][м].tolist())
            npv[к] += float(г1['npv'][м].sum())
    return {'op_наш': из_['наш'], 'op_л1': из_['л1'], 'npv_наш': npv['наш'] / B, 'npv_л1': npv['л1'] / B}

def сторона(знач: np.ndarray, порог: float, направление: str) -> np.ndarray:
    нб = np.isnan(знач)
    м = знач < порог if направление == 'низ' else знач > порог
    return np.where(нб, False, м)

def пи(тб: pl.DataFrame, имена: tuple, порог: dict, оп_л1: list, оп_наш: list, npv_л1: float, npv_наш: float) -> dict:
    инд = {o: i for i, o in enumerate(тб['op_id'].to_list())}
    i_л1 = np.array([инд[o] for o in оп_л1])
    i_наш = np.array([инд[o] for o in оп_наш])
    npv_стб = тб['NPV наш млн'].to_numpy()
    за_л1 = np.ones(тб.height, bool)
    за_наш = np.ones(тб.height, bool)
    пропусков = 0
    for имя in имена:
        напр = dict(ПРИЗНАКИ)[имя]
        v = тб[имя].cast(pl.Float64).to_numpy()
        пропусков += int(np.isnan(v).sum())
        за_л1 &= сторона(v, порог[имя], напр)
        за_наш &= сторона(v, порог[имя], 'верх' if напр == 'низ' else 'низ')
    верно_л1 = int(за_л1[i_л1].sum())
    верно_наш = int(за_наш[i_наш].sum())
    всего = len(оп_л1) + len(оп_наш)
    зн_л1, зн_наш = (abs(npv_л1), abs(npv_наш))
    if зн_л1 == 0.0 or зн_наш == 0.0:
        raise ValueError('сумма NPV группы равна нулю: самопроверка 3.301 обязана была упасть раньше, значит группы составлены не из тех операций')
    д_л1 = abs(float(npv_стб[i_л1][за_л1[i_л1]].sum()) / 1000.0) / зн_л1
    д_наш = abs(float(npv_стб[i_наш][за_наш[i_наш]].sum()) / 1000.0) / зн_наш
    return {'пи': (верно_л1 + верно_наш) / всего, 'верно_л1': верно_л1, 'верно_наш': верно_наш, 'всего': всего, 'деньги_л1': д_л1, 'деньги_наш': д_наш, 'пропусков': пропусков}

def прошёл(р: dict, базис: float) -> bool:
    return р['пи'] >= ПОРОГ_ПИ and р['пи'] - базис >= ПОРОГ_НАД_БАЗИСОМ and (р['деньги_л1'] >= ПОРОГ_ДЕНЕГ) and (р['деньги_наш'] >= ПОРОГ_ДЕНЕГ)

def печать_распределений(тб: pl.DataFrame, гр: dict, имя_пары: str) -> None:
    инд = {o: i for i, o in enumerate(тб['op_id'].to_list())}
    части = {'Л1 берёт лишнее': гр['op_л1'], 'Л1 роняет нужное': гр['op_наш'], 'ВСЯ совокупность': тб['op_id'].to_list()}
    print(f'\n--- ПАРА {имя_пары}: распределения семи признаков и трёх печатных ---')
    print(f"{'признак':30s} {'группа':18s} {'n':>5s} {'медиана':>10s} {'кварт.1':>10s} {'кварт.3':>10s} {'среднее':>10s} {'пропусков':>9s}")
    for имя in [и for и, _ in ПРИЗНАКИ] + list(ТОЛЬКО_ПЕЧАТЬ):
        v = тб[имя].cast(pl.Float64).to_numpy()
        for метка, оп in части.items():
            i = np.array([инд[o] for o in оп])
            x = v[i]
            x_ = x[~np.isnan(x)]
            ф = lambda z: f'{z:10.4f}' if len(x_) else f"{'нет':>10s}"
            print(f"{имя:30s} {метка:18s} {len(оп):5d} {(ф(np.median(x_)) if len(x_) else 'нет'):>10s} {(ф(np.percentile(x_, 25)) if len(x_) else 'нет'):>10s} {(ф(np.percentile(x_, 75)) if len(x_) else 'нет'):>10s} {(ф(x_.mean()) if len(x_) else 'нет'):>10s} {int(np.isnan(x).sum()):9d}")
    print(f'\n--- ПАРА {имя_пары}: ТИП, доли двенадцати кодов (ведомость 3.303) ---')
    типы = sorted(тб['тип'].unique().to_list())
    print(f"{'тип':8s} {'доля матч.':>10s} " + ' '.join((f'{м:>22s}' for м in части)))
    тип_по_оп = dict(zip(тб['op_id'].to_list(), тб['тип'].to_list()))
    дм = dict(zip(тб['тип'].to_list(), тб['доля матчасти типа'].to_list()))
    for т in типы:
        стб = []
        for метка, оп in части.items():
            k = sum((тип_по_оп[o] == т for o in оп))
            стб.append(f'{k:6d} ({k / len(оп) * 100:5.1f}%)' if оп else 'нет')
        print(f"{т:8s} {дм.get(т, float('nan')):10.3f} " + ' '.join((f'{s:>22s}' for s in стб)))

